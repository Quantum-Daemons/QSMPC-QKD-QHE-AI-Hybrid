#!/bin/sh
# Regenerates requirements.lock, which the API image and CI install with --require-hashes (Round 86, the owner's
# choice). The floors stay in requirements-*.txt; this records what they resolved to, so two builds of one commit
# install the same bytes and a dependency moves only when someone regenerates this. It holds the CPU tier the image and CI use: core, API,
# FHE and AI, with torch from the PyTorch CPU index. It also writes requirements-gpu.lock, the GPU tier this machine trains and
# simulates with, from PyTorch's CUDA 13 index: its own lock, since a CUDA torch and a CPU torch cannot be one resolution.
#
#   bash scripts/lock_requirements.sh
#
# tests/test_requirements_lock_is_current.py fails if an input changes and this was not run. Needs uv and network access.
set -eu
cd "$(dirname "$0")/.."
INPUTS="requirements-core.txt requirements-api.txt requirements-fhe.txt requirements-ai.txt"
# shellcheck disable=SC2086
# Seeded with the current lock, because uv prefers the versions already in its output file: a changed input then moves
# only what it requires. Compiled into an empty file, the first regeneration after Round 86 (one floor, openfhe) would
# have re-resolved every package against that day's index.
[ -f requirements.lock ] && grep -v '^# ' requirements.lock > requirements.lock.new
uv pip compile $INPUTS --python-version 3.12 --python-platform x86_64-unknown-linux-gnu --generate-hashes \
  --index-url https://pypi.org/simple --extra-index-url https://download.pytorch.org/whl/cpu \
  --index-strategy unsafe-best-match --no-header --quiet -o requirements.lock.new
# The digest covers requirement lines only, so a comment does not make the lock stale.
# shellcheck disable=SC2086
DIGEST=$(cat $INPUTS | sed -E 's/#.*//; s/^[[:space:]]+//; s/[[:space:]]+$//; /^$/d' | sha256sum | cut -d' ' -f1)
{
  echo "# Generated by scripts/lock_requirements.sh. Do not edit by hand."
  echo "# inputs sha256: $DIGEST"
  cat requirements.lock.new
} > requirements.lock
rm -f requirements.lock.new
echo "wrote requirements.lock ($(grep -c '==' requirements.lock) packages)"

# The GPU tier, the same way.
GPU_INPUTS="requirements-gpu.txt"
[ -f requirements-gpu.lock ] && grep -v '^# ' requirements-gpu.lock > requirements-gpu.lock.new
uv pip compile $GPU_INPUTS --python-version 3.12 --python-platform x86_64-unknown-linux-gnu --generate-hashes \
  --index-url https://pypi.org/simple --extra-index-url https://download.pytorch.org/whl/cu130 \
  --index-strategy unsafe-best-match --no-header --quiet -o requirements-gpu.lock.new
GPU_DIGEST=$(cat $GPU_INPUTS | sed -E 's/#.*//; s/^[[:space:]]+//; s/[[:space:]]+$//; /^$/d' | sha256sum | cut -d' ' -f1)
{
  echo "# Generated by scripts/lock_requirements.sh. Do not edit by hand."
  echo "# inputs sha256: $GPU_DIGEST"
  cat requirements-gpu.lock.new
} > requirements-gpu.lock
rm -f requirements-gpu.lock.new
echo "wrote requirements-gpu.lock ($(grep -c '==' requirements-gpu.lock) packages)"
