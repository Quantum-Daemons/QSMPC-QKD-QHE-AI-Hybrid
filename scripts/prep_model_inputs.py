#!/usr/bin/env python3
"""Build **model-native** demo inputs so the browser can actually run the published HF models.

Why this exists
---------------
Until Round 18 the browser tier could never have worked, and a 401 on the private HF repos was
masking it. Each use-case page bundles a small sample for the *crypto* pipeline -- 8 features, so a
CKKS linear layer and a garbled-circuit argmax stay tractable in a tab -- but the model published
for that page was trained on a different corpus with a different input entirely:

    page        bundled pipeline sample              published model expects
    finance     PaySim, 8 engineered features        AMLworld, 32 graph/temporal features
    medical     Wisconsin WDBC, 8 tabular features   BreastMNIST, [1,1,28,28] images
    satellite   NASA SMAP/MSL, 6ch x 8 steps         ESA-ADB ch 41-46, [1,250,6] windows

So the fix is not a tensor reshape. Each published model needs a real sample drawn from the
distribution it was actually trained on. This script writes those, next to -- not instead of -- the
pipeline samples, which keep doing their own job.

Preprocessing travels WITH the data, deliberately
-------------------------------------------------
Writing this script, the first attempt scored the medical ResNet-18 at 0.4615 on the real test
split against a recorded 0.8782 -- below the 0.7308 majority-class baseline. The model was fine.
The mistake was applying `/255` and omitting the `(x-0.5)/0.5` step on line 65 of
`scripts/train/medical_breastmnist.py`. A browser reimplementing normalisation by hand would make
exactly that mistake and show a confidently wrong number with no error anywhere.

So every file this writes carries an explicit ``input.preprocessing`` list that the browser applies
verbatim, plus ``expected.accuracy`` measured here on these very rows. The browser re-checks its own
result against that figure and reports a mismatch instead of rendering it. That converts "MEASURED"
from an assertion into something the page proves each time it runs.

Usage (maintainer, one-time; not part of any runtime path)::

    export QSH_DATA_ROOT=$PWD/data-full
    python scripts/prep_model_inputs.py --usecase medical_fl
    python scripts/prep_model_inputs.py --usecase finance_aml
    python scripts/prep_model_inputs.py --usecase satellite_comms

Corpora are fetched by the commands in ``src/qsh/models/datasets.py`` (AMLWORLD_FETCH, ESA_FETCH);
BreastMNIST is fetched by ``medmnist`` itself. None of them are redistributed by this repository --
only the small derived samples below, whose licences are recorded in DATA_LICENSES.md.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))
sys.path.insert(0, str(REPO / "scripts"))

OUT_ROOT = REPO / "web" / "public" / "data"

#: How many rows each use case ships, chosen per model rather than globally, because the right
#: answer depends entirely on how big one row is.
#:
#:  * medical    -- the ENTIRE official BreastMNIST test split. 156 x 28 x 28 uint8 is ~0.4 MB raw
#:                  and digits compress well, so the browser can reproduce the model's PUBLISHED
#:                  test metric exactly rather than a subsample of it. That is a much stronger
#:                  claim and it costs almost nothing.
#:  * finance    -- 8192 rows of 32 floats. A 1-in-981 positive rate needs volume before an
#:                  accuracy figure means anything, and this narrows the 95% interval to ~+/-0.6pp
#:                  against ~+/-2.6pp at 512.
#:  * satellite  -- 128 windows. One window is 250 x 6 = 1500 floats, still the heaviest row here.
#:
#: The full training corpora are deliberately NOT shipped: AMLworld is 475 MB, ESA-ADB is 3.6 GB,
#: and neither may be redistributed (see DATA_LICENSES.md). A browser does not need the training
#: corpus to verify a model -- it needs a held-out sample large enough to be worth believing.
N_SAMPLES = {"medical_fl": None, "finance_aml": 8192, "satellite_comms": 128,
             # The whole OPS-SAT test split: 529 rows of 19 floats is ~200 KB, so
             # the browser can reproduce the published-split number exactly rather
             # than a subsample of it.
             "satellite_opssat": None,
             # Both entire held-out splits. Telecom's corpus is generated by this repository, so
             # there is no licence question and no reason to subsample; medical's is the official
             # BreastMNIST test split, the same one medical_fl.resnet18 ships, so the two teachers
             # are verified on identical rows and the comparison between them is like for like.
             "telecom_ids": None, "medical_resnet50": None}


def _session(model_dir: str, prefer_int8: bool = True):
    """The published graph, preferring the int8 the browser tier actually downloads."""
    import onnxruntime as ort

    base = REPO / "models" / model_dir / "onnx"
    for name in (["model_int8.onnx", "model.onnx"] if prefer_int8 else ["model.onnx"]):
        p = base / name
        if p.exists():
            return ort.InferenceSession(str(p), providers=["CPUExecutionProvider"]), name
    raise FileNotFoundError(f"no ONNX graph under {base}")



def _apply_preprocessing_step(x: np.ndarray, step: str) -> np.ndarray:
    """Apply one `input.preprocessing` instruction, the same strings the browser parses.

    Kept as a tiny interpreter rather than hardcoded arithmetic so a generator and the browser
    cannot drift: if a step is added here it has to be added there, and an unknown step raises
    instead of being skipped.
    """
    s = step.strip().lower()
    if s.startswith("divide by "):
        return x / float(s.removeprefix("divide by "))
    if s.startswith("subtract "):
        return x - float(s.removeprefix("subtract "))
    if s.startswith("multiply by "):
        return x * float(s.removeprefix("multiply by "))
    raise ValueError(f"unknown preprocessing step {step!r} - add it here and in onnxInference.ts")


def _write(usecase: str, payload: dict) -> Path:
    """Write beside the model, not into the web bundle.

    The evaluation sample belongs in the model's own HF repo at the same pinned commit: the sample
    and the weights it evaluates then travel together and cannot drift apart, the demo image stops
    carrying 1.6 MB it does not need, and HF's CDN serves the bytes instead of a 12 GB VPS. That
    last point is what makes a larger sample affordable -- 8192 AMLworld rows narrow the 95%
    interval on accuracy from about +/-2.6pp to +/-0.6pp, and none of it touches this repository.
    """
    from qsh.models import registry

    key = _MODEL_KEY[usecase]
    out = REPO / registry.ARTIFACT_DIRS[key] / "eval_sample.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, indent=1) + "\n")
    size = out.stat().st_size
    print(f"  wrote {out.relative_to(REPO)}  ({size/1024:.0f} KB)")
    exp = payload["expected"]
    if "minority_class_f1" in exp:
        # Checked first: three of the four students are published with THIS metric, and a payload
        # carrying both would otherwise be summarised by the more flattering one.
        f1, base = exp["minority_class_f1"], exp.get("all_positive_f1") or 0.0
        ratio = f" ({f1 / base:.1f}x)" if base else ""
        print(f"    expected rare-class F1 on these rows: {f1:.4f} "
              f"(all-positive baseline {base:.4f}{ratio})")
    elif "accuracy" in exp:
        acc, base = exp["accuracy"], exp["majority_baseline"]
        print(f"    expected accuracy on these rows: {acc:.4f} "
              f"(majority-class baseline {base:.4f})")
        if acc <= base:
            print("    NOTE: at or below the majority baseline. This model does not beat guessing "
                  "the commonest label on these rows, and the page will say so rather than not.")
    else:
        print(f"    expected forecast MAE on these windows: {exp['mae']:.4f} "
              f"(persistence baseline {exp['persistence_mae']:.4f})")
    return out


#: Which model each use case's evaluation sample belongs to.
_MODEL_KEY = {
    "medical_fl": "medical_fl.resnet18",
    "finance_aml": "finance_aml.gbm",
    "satellite_comms": "satellite_comms.telemanom",
    "satellite_opssat": "satellite_comms.opssat",
    "telecom_ids": "telecom_ids.qml",
    "medical_resnet50": "medical_fl.resnet50",
    "medical_student": "medical_fl.student",
    "opssat_student": "satellite_comms.opssat_student",
    "finance_student": "finance_aml.student",
}


# --------------------------------------------------------------------------------------------- #
#  medical_fl -- BreastMNIST 28x28, the corpus medical_fl.resnet18 was actually trained on
# --------------------------------------------------------------------------------------------- #
def build_medical(rng: np.random.Generator) -> dict:
    import os

    from medmnist import INFO, BreastMNIST

    root = os.path.join(os.environ["QSH_DATA_ROOT"], "raw", "medmnist")
    ds = BreastMNIST(split="test", download=True, root=root)
    imgs, labels = ds.imgs, ds.labels.ravel()

    # Stratified so the sample cannot be all-majority; the accuracy self-check would be meaningless.
    # None => the whole official test split, so the figure below IS the published test metric.
    want = N_SAMPLES["medical_fl"]
    if want is None:
        idx = np.arange(len(labels))
    else:
        idx = np.concatenate([
            rng.choice(np.flatnonzero(labels == c), size=want // 2, replace=False) for c in (0, 1)
        ])
    rng.shuffle(idx)
    x_u8, y = imgs[idx], labels[idx]

    x = x_u8.astype(np.float32)[:, None, :, :] / 255.0
    x = (x - 0.5) / 0.5                               # train/medical_breastmnist.py:64-65
    sess, graph = _session("medical_breastmnist_resnet18")
    pred = sess.run(None, {sess.get_inputs()[0].name: x})[0].argmax(1)

    return {
        "provenance": (
            "real MedMNIST v2 BreastMNIST test-split images (Yang et al., Scientific Data 10:41, "
            "2023; CC BY 4.0), derived from the Al-Dhabyani et al. BUSI ultrasound dataset. These "
            "are the images medical_fl.resnet18 was trained and evaluated on -- unlike the Wisconsin "
            "WDBC sample this page uses for the FHE/MPC pipeline, which is a different corpus."
        ),
        "input": {
            "shape": [1, 1, 28, 28], "dtype": "float32",
            # Applied by the browser verbatim. Omitting the second step scores 0.4615 instead of
            # 0.8782 -- silently, with no error. See the module docstring.
            "preprocessing": ["divide by 255", "subtract 0.5", "divide by 0.5"],
            "layout": "samples[i] is a flat row-major 28*28 uint8 image, values 0-255",
        },
        "classes": INFO["breastmnist"]["label"],
        "samples": x_u8.reshape(len(idx), -1).astype(int).tolist(),
        "labels": y.astype(int).tolist(),
        "expected": {
            "graph": graph,
            "accuracy": float((pred == y).mean()),
            "majority_baseline": float(max(np.bincount(y)) / len(y)),
            "note": ("Measured here with onnxruntime on exactly these rows. The browser must "
                     "reproduce it to within tolerance or report a mismatch rather than render it."),
        },
    }


# --------------------------------------------------------------------------------------------- #
#  finance_aml -- AMLworld HI-Small, the 32 engineered features finance_aml.gbm expects
# --------------------------------------------------------------------------------------------- #
def build_finance(rng: np.random.Generator) -> dict:
    # Reuse the training script's own feature engineering rather than reimplementing 32 columns --
    # a second implementation would drift from the model on the first edit.
    from train.finance_aml import FEATURES, graph_features  # type: ignore

    from qsh.models import datasets as D

    # load_amlworld normalises "Is Laundering" -> "label" (datasets.py:84-91); the training script
    # reads that name too, so use it rather than the raw CSV header.
    df = D.load_amlworld(nrows=400_000)
    if "label" not in df:
        raise SystemExit(f"AMLworld frame has no 'label' column; got {list(df.columns)[:12]}")
    y_all = df["label"].to_numpy().astype(int)

    feats = graph_features(df)
    X_all = np.asarray(feats[list(FEATURES)].to_numpy(dtype=np.float32)
                       if hasattr(feats, "columns") else feats, dtype=np.float32)

    pos = np.flatnonzero(y_all == 1)
    neg = np.flatnonzero(y_all == 0)
    # 1-in-981 prevalence: a random draw would almost surely contain zero positives and the
    # self-check would say nothing. Force a visible minority so the number means something.
    want = N_SAMPLES["finance_aml"]
    take_pos = min(len(pos), want // 4)
    idx = np.concatenate([rng.choice(pos, take_pos, replace=False),
                          rng.choice(neg, want - take_pos, replace=False)])
    rng.shuffle(idx)
    x, y = X_all[idx], y_all[idx]

    # Round BEFORE predicting. The payload ships 6-decimal values, so an expectation computed on
    # the unrounded array is an expectation for numbers the browser never sees. On a tree ensemble
    # that shows up as split-boundary flips: the OPS-SAT model read 95.1% in-browser against a
    # 96.6% expectation computed this way, inside tolerance but not a reproduction.
    x = np.asarray(x, dtype=float).round(6)
    sess, graph = _session("finance_aml_gbm")
    out = sess.run(None, {sess.get_inputs()[0].name: x.astype(np.float32)})
    scores = next((o for o in out if getattr(o, "ndim", 0) == 2 and o.shape[1] > 1), out[0])
    pred = np.asarray(scores).argmax(1)

    return {
        "provenance": (
            "IBM AMLworld HI-Small (Altman et al., Kaggle "
            "ealtman2019/ibm-transactions-for-anti-money-laundering-aml, CDLA-Sharing-1.0). The "
            "corpus is entirely SYNTHETIC by IBM's own statement -- generated by a multi-agent "
            "virtual world, not real customer data. An earlier revision of this line opened with "
            "the word 'real' and then said synthetic in its next sentence; what is real is the "
            "provenance, not the transactions. These are unmodified rows of the published corpus, "
            "carrying the engineered features finance_aml.gbm was actually trained on, unlike the "
            "8-feature PaySim sample this page uses for the FHE/MPC pipeline."
        ),
        "input": {"shape": [1, len(FEATURES)], "dtype": "float32",
                  "preprocessing": [], "layout": "samples[i] is one row of the 32 features below"},
        "feature_names": list(FEATURES),
        "samples": np.asarray(x, dtype=float).tolist(),  # already rounded above
        "labels": y.astype(int).tolist(),
        "expected": {
            "graph": graph,
            "accuracy": float((pred == y).mean()),
            "majority_baseline": float(max(np.bincount(y)) / len(y)),
            "note": ("Stratified to contain positives -- AMLworld's real prevalence is ~1 in 981, "
                     "so an unstratified draw would be all-negative and accuracy would be vacuous."),
        },
    }


# --------------------------------------------------------------------------------------------- #
#  satellite_comms -- ESA-ADB Mission1 channels 41-46, [1,250,6] windows
# --------------------------------------------------------------------------------------------- #
def build_satellite(rng: np.random.Generator) -> dict:
    """ESA-ADB Mission1 channels 41-46, windowed exactly as scripts/train/satellite_telemanom.py does.

    Telemanom is a FORECASTER, not a classifier: [1,250,6] in, [1,6] next-step prediction out. So the
    self-check here is forecast error against the true next values, not an accuracy. Reproducing the
    model's headline event-wise F0.5 would mean reimplementing non-parametric dynamic thresholding in
    the browser, which is a different and much larger claim than "the published graph executes here
    and predicts what it predicted offline".
    """
    from qsh.models import datasets as D
    from qsh.models import registry

    seq, chans = 250, list(D.ESA_MISSION1_LIGHTWEIGHT)
    # Mirror the training pipeline step for step; a different resample or normalisation would make
    # the browser's numbers incomparable with the recorded ones for reasons nobody could see.
    # Read the cadence the model was TRAINED at rather than hardcoding one. Hardcoding 60s here
    # while the published model was trained at 300s is precisely how Round 18 came to report the
    # forecaster as 19-22x worse than persistence: it was being fed data at the wrong sampling
    # rate. At the correct cadence the same model is about 2.9x BETTER than persistence. The
    # preprocessing has to come from the artefact, not from a constant in a second file.
    resample = str(registry.achieved("satellite_comms.telemanom").get("resample") or "300s")
    raw = D.load_esa_channels()
    df = raw.resample(resample).mean().ffill().bfill()
    values = df.to_numpy(dtype=np.float32)
    mu, sigma = values.mean(0), values.std(0) + 1e-8
    values = (values - mu) / sigma                       # train script lines 164-166

    # 250x6 per window is 1500 floats, so keep this small -- the comparison against
    # persistence is stable well below N_SAMPLES and the payload has to ship.
    n_windows = N_SAMPLES["satellite_comms"]
    starts = rng.choice(np.arange(0, len(values) - seq - 1), size=n_windows, replace=False)
    x = np.stack([values[s:s + seq] for s in starts]).astype(np.float32)
    y_next = np.stack([values[s + seq] for s in starts]).astype(np.float32)

    # Measure the graph the BROWSER will fetch. browserModel() prefers int8 where one exists
    # and is runnable, so measuring fp32 here published an expectation for a graph no visitor
    # would ever run -- and nothing checked, until the graph assertion was added.
    sess, graph = _session("satellite_telemanom", prefer_int8=True)
    pred = np.asarray(sess.run(None, {sess.get_inputs()[0].name: x})[0], dtype=np.float32)
    mae = float(np.abs(pred - y_next).mean())
    # What predicting "no change from the last observed step" would score. A forecaster that cannot
    # beat persistence is not forecasting, and the browser should be able to see that too.
    persistence_mae = float(np.abs(x[:, -1, :] - y_next).mean())

    return {
        "task": "forecast",
        "provenance": (
            "real ESA Anomaly Dataset (ESA-ADB) Mission1 lightweight channels 41-46 "
            "(Zenodo 12528696, CC BY 3.0 IGO). Missions are anonymised Mission1/2/3 -- they are not "
            "named Sentinel anything. Resampled to 60s and z-scored exactly as the training script "
            "does. These are the windows satellite_comms.telemanom was trained on, unlike the NASA "
            "SMAP/MSL sample this page uses for the FHE/MPC pipeline."
        ),
        "input": {"shape": [1, seq, len(chans)], "dtype": "float32", "preprocessing": [],
                  "layout": f"samples[i] is {seq} timesteps x {len(chans)} channels at {resample} "
                            "cadence, row-major, already resampled and z-scored"},
        "channels": chans,
        "samples": x.reshape(len(x), -1).round(4).tolist(),
        "targets": y_next.round(4).tolist(),
        "expected": {
            "graph": graph,
            "mae": mae,
            "persistence_mae": persistence_mae,
            "note": ("Mean absolute error of the next-step forecast, measured here with onnxruntime "
                     "on exactly these windows. persistence_mae is what predicting no change would "
                     "score, so a reader can tell whether the model is doing anything."),
        },
    }



# --------------------------------------------------------------------------------------------- #
#  satellite_opssat -- OPS-SAT-AD, the whole published test split
# --------------------------------------------------------------------------------------------- #
def build_satellite_opssat(rng: np.random.Generator) -> dict:
    """The benchmark's own test partition, unmodified and unsampled.

    No stratification and no draw: OPS-SAT-AD ships a train/test split and the published scores are
    reported on it, so taking anything other than the whole partition would produce a number that
    is not the one the 30 baselines are quoted against.
    """
    from qsh.models import datasets

    x, y = datasets.opssat_ad("test")
    x = np.asarray(x, dtype=np.float32)

    # Round before predicting, so `expected` describes the values the payload actually ships.
    x = np.asarray(x, dtype=float).round(6)
    sess, graph = _session("satellite_opssat")
    out = sess.run(None, {sess.get_inputs()[0].name: x.astype(np.float32)})
    scores = next((o for o in out if getattr(o, "ndim", 0) == 2 and o.shape[1] > 1), out[0])
    pred = np.asarray(scores).argmax(1)

    return {
        "provenance": (
            "OPS-SAT-AD (Kotowski et al., 'The OPS-SAT benchmark for detecting anomalies in "
            "satellite telemetry', Scientific Data 12, 2025; Zenodo 10.5281/zenodo.12588359, "
            "CC BY 4.0). Real telemetry from ESA's OPS-SAT CubeSat, which reentered in May 2024. "
            "These are the 19 precomputed per-segment features of the benchmark's own TEST "
            "partition, entire and unsampled, so the figure below is the one the dataset's 30 "
            "published baselines are quoted against. Not comparable with the Telemanom model on "
            "this same page: that one forecasts continuous ESA-ADB series, this one classifies "
            "pre-segmented fragments."
        ),
        "input": {"shape": [1, x.shape[1]], "dtype": "float32", "preprocessing": [],
                  "layout": "samples[i] is one segment's 19 features, in the order below"},
        "feature_names": list(datasets.OPSSAT_FEATURES),
        "samples": np.asarray(x, dtype=float).tolist(),  # already rounded above
        "labels": y.astype(int).tolist(),
        "expected": {
            "graph": graph,
            "accuracy": float((pred == y).mean()),
            "majority_baseline": float(max(np.bincount(y)) / len(y)),
            "note": ("The whole published test split, so this reproduces the benchmark's own "
                     "partition rather than a resample of it."),
        },
    }



# --------------------------------------------------------------------------------------------- #
#  telecom_ids -- the synthetic QKD-attack telemetry this repository generates
# --------------------------------------------------------------------------------------------- #
def build_telecom(rng: np.random.Generator) -> dict:
    """The same held-out quarter `scripts/train/telecom_ids.py` scores on.

    Regenerated from the same seed and split rather than stored, so the sample cannot drift from
    the corpus the model was trained against. The data is synthetic and generated here, so unlike
    every other use case the FULL split ships with no licence question at all.
    """
    from sklearn.model_selection import train_test_split

    from qsh.qml_ids.attacks import ATTACKS, generate

    # Mirrors scripts/train/telecom_ids.py: n_per_class=300, seed=42, stratified 25% test split.
    x_all, y_all, feature_names = generate(n_per_class=300, seed=42)
    _, x, _, y = train_test_split(x_all, y_all, test_size=0.25, random_state=42, stratify=y_all)
    x = np.asarray(x, dtype=float).round(6)

    sess, graph = _session("telecom_qml_ids")
    out = sess.run(None, {sess.get_inputs()[0].name: x.astype(np.float32)})
    scores = next((o for o in out if getattr(o, "ndim", 0) == 2 and o.shape[1] > 1), out[0])
    pred = np.asarray(scores).argmax(1)

    return {
        "provenance": (
            "SYNTHETIC QKD-attack telemetry generated by src/qsh/qml_ids/attacks.py. The eight "
            "classes are seven attack types plus normal traffic, a structure taken from Al-Kuwari "
            "et al. (arXiv:2509.14282); no number from that paper is reproduced here. It is "
            "synthetic because no real corpus with unambiguous commercial terms exists - UNSW-NB15 "
            "needs the authors' agreement, and the CIC's institute FAQ and its CICIDS2017 dataset "
            "page state conflicting terms. This is the whole held-out quarter of the same "
            "seed-42 draw the published model was trained against, so the figure below is the "
            "model's own test metric rather than a resample of it."
        ),
        "input": {"shape": [1, x.shape[1]], "dtype": "float32", "preprocessing": [],
                  "layout": "samples[i] is one QKD session's features, in the order below"},
        "feature_names": list(feature_names),
        "samples": np.asarray(x, dtype=float).tolist(),
        "labels": np.asarray(y, dtype=int).tolist(),
        "expected": {
            "graph": graph,
            "accuracy": float((pred == np.asarray(y)).mean()),
            "majority_baseline": float(max(np.bincount(np.asarray(y, dtype=int))) / len(y)),
            "note": ("Eight balanced classes, so the majority baseline is 1/8. The published "
                     "comparison is per-class F1: aggregate accuracy is the metric that makes a "
                     "broken detector look fine (Engelen et al., WTMC 2021)."),
        },
        "class_names": list(ATTACKS),
    }


# --------------------------------------------------------------------------------------------- #
#  medical_resnet50 -- the SAME BreastMNIST test split resnet18 uses, so the two compare directly
# --------------------------------------------------------------------------------------------- #
def build_medical_resnet50(rng: np.random.Generator) -> dict:
    """Identical rows to the ResNet-18 sample, scored by the ResNet-50 graph.

    The point of this model is a published negative result - MedMNIST v2 reports ResNet-50 BELOW
    ResNet-18 on this corpus - and a negative result nobody can reproduce is just an assertion.
    Same split, same preprocessing, different graph.
    """
    payload = build_medical(rng)
    # `samples` are stored RAW (0-255) with the normalisation carried in `input.preprocessing` for
    # the consumer to apply -- that is the whole point of shipping preprocessing with the data.
    # Feeding them unprocessed makes any model look degenerate: it scored exactly the majority
    # baseline, all-one-class, which is what a saturated ResNet does on out-of-range inputs.
    x = np.asarray(payload["samples"], dtype=np.float32).reshape(-1, 1, 28, 28)
    for step in payload["input"]["preprocessing"]:
        x = _apply_preprocessing_step(x, step)
    y = np.asarray(payload["labels"], dtype=int)

    sess, graph = _session("medical_breastmnist_resnet50")
    out = sess.run(None, {sess.get_inputs()[0].name: x})
    scores = next((o for o in out if getattr(o, "ndim", 0) == 2 and o.shape[1] > 1), out[0])
    pred = np.asarray(scores).argmax(1)

    payload["provenance"] = (
        payload["provenance"]
        + " Scored here by medical_fl.resnet50, on exactly the rows medical_fl.resnet18 is scored "
          "on, because the published claim being tested is that the deeper network does WORSE: "
          "MedMNIST v2 reports ResNet-50 at AUC 0.857 against ResNet-18's 0.901."
    )
    payload["expected"] = {
        "graph": graph,
        "accuracy": float((pred == y).mean()),
        "majority_baseline": float(max(np.bincount(y)) / len(y)),
        "note": ("Same rows as the ResNet-18 sample. A lower number here is the reproduction, not "
                 "a failure."),
    }
    return payload




# --------------------------------------------------------------------------------------------- #
#  The four CKKS-linear students
# --------------------------------------------------------------------------------------------- #
#  These are the models that actually run under homomorphic encryption, and until now none of them
#  shipped a held-out sample -- so the E2E simulator could select one and could only report
#  "DID NOT RUN".
#
#  Two decisions apply to all of them.
#
#  ROWS ARE MODEL-READY. The browser's applyPreprocessing() is per-scalar and understands three
#  instructions; it cannot apply a 32-length mean/scale vector or an area resize, and it throws
#  rather than guess. So the transform is applied HERE and the sample ships `preprocessing: []`,
#  which is what the finance teacher's sample already does. The alternative -- teaching the browser
#  vector arithmetic -- would put the students' preprocessing in two places that must agree.
#
#  THE SCALER COMES FROM weights.json, never re-fitted. A StandardScaler fitted here on the test
#  split would be a different transform from the one the student was trained under, and would
#  produce a plausible, wrong number rather than an error. That is the exact trap Round 20 recorded
#  when these students published coefficients without their scaler.


def _student_scaler(model_dir: str) -> tuple[np.ndarray, np.ndarray]:
    """The PUBLISHED mean/scale, or a loud failure. Never re-fitted from data seen here."""
    w = json.loads((REPO / "models" / model_dir / "weights.json").read_text())
    inp = w.get("input") or {}
    if "mean" not in inp or "scale" not in inp:
        raise SystemExit(
            f"{model_dir}/weights.json publishes no scaler, so its ONNX cannot be fed correctly "
            f"from here. Re-run its training script with distil.save_student(..., scaler=...) and "
            f"republish before generating a sample -- do not guess one.")
    return np.asarray(inp["mean"], dtype=float), np.asarray(inp["scale"], dtype=float)


def _predict(model_dir: str, x: np.ndarray) -> np.ndarray:
    """Argmax of the published student graph. fp32: these students ship no int8 artefact."""
    sess, _ = _session(model_dir, prefer_int8=False)
    out = sess.run(None, {sess.get_inputs()[0].name: x.astype(np.float32)})
    scores = next((o for o in out if getattr(o, "ndim", 0) == 2 and o.shape[1] > 1), out[0])
    return np.asarray(scores).argmax(1)


def _f1_over_baseline(y: np.ndarray, pred: np.ndarray) -> tuple[float, float, float]:
    """Rare-class F1, the F1 of flagging everything, and the ratio between them.

    The ratio is the part that survives a change of prevalence. Rare-class F1 does not: the finance
    student scores 0.3337 on the enriched sample below and 0.0178 on the full corpus, a 19x gap that
    is entirely an artefact of how many positives each contains. Against its own all-positive
    baseline it is 9.3x on one and 8.7x on the other, which is the same model described twice.
    """
    from qsh.models import metrics

    f1 = float(metrics.minority_class_f1(y, pred))
    prevalence = float(np.mean(y == 1))
    all_pos = (2 * prevalence) / (1 + prevalence) if prevalence else 0.0
    return f1, all_pos, (f1 / all_pos if all_pos else float("nan"))


def build_medical_student(rng: np.random.Generator) -> dict:
    """BreastMNIST test split at 14x14, the resolution the student was distilled at.

    Reproduces the recorded fidelity exactly: accuracy 0.730769 on all 156 rows.
    """
    import os

    from medmnist import BreastMNIST

    from qsh.ai.cnn_layers import downsample

    root = os.path.join(os.environ["QSH_DATA_ROOT"], "raw", "medmnist")
    ds = BreastMNIST(split="test", download=False, root=root)
    imgs, y = ds.imgs, ds.labels.ravel().astype(int)

    x = imgs.astype(np.float32)[:, None, :, :] / 255.0
    x = (x - 0.5) / 0.5                                  # train/medical_breastmnist.py
    x14 = np.asarray(downsample(x, 14), dtype=float)     # F.interpolate(mode="area"), as distilled
    x14 = x14.round(6)                                   # round BEFORE predicting
    pred = _predict("medical_breastmnist_student", x14)

    return {
        "task": "classification",
        "provenance": (
            "MedMNIST v2 BreastMNIST test split (Yang et al., Scientific Data 10:41, 2023; "
            "CC BY 4.0), derived from the Al-Dhabyani et al. BUSI ultrasound dataset. Normalised "
            "and area-resized to 14x14 here, which is the resolution this student was distilled at "
            "and the one its encrypted convolution runs on -- the ResNet-18 teacher on this same "
            "page runs at 28x28, so the two are not interchangeable inputs."),
        "input": {"shape": [1, 1, 14, 14], "dtype": "float32", "preprocessing": [],
                  "layout": "samples[i] is one 14x14 image, row-major, already normalised"},
        "classes": {"0": "benign/normal", "1": "malignant"},
        "samples": x14.reshape(len(y), -1).tolist(),
        "labels": y.tolist(),
        "expected": {
            "graph": "model.onnx",
            "accuracy": float((pred == y).mean()),
            "majority_baseline": float(max(np.bincount(y)) / len(y)),
            "note": ("The whole official test split, and the same rows the registry's recorded "
                     "student accuracy was measured on, so this reproduces that figure rather than "
                     "resampling it."),
        },
    }


def build_opssat_student(rng: np.random.Generator) -> dict:
    """OPS-SAT-AD test partition, z-scored by the published scaler.

    Reproduces the recorded fidelity exactly: minority-class F1 0.864865 on all 529 segments.
    """
    from qsh.models import datasets

    x, y = datasets.opssat_ad("test")
    y = np.asarray(y, dtype=int)
    mean, scale = _student_scaler("satellite_opssat_student")
    z = ((np.asarray(x, dtype=float) - mean) / scale).round(6)   # round BEFORE predicting
    pred = _predict("satellite_opssat_student", z)
    f1, all_pos, ratio = _f1_over_baseline(y, pred)

    return {
        "task": "classification",
        "provenance": (
            "OPS-SAT-AD (Kotowski et al., Scientific Data 12, 2025; Zenodo "
            "10.5281/zenodo.12588359, CC BY 4.0). Real telemetry from ESA's OPS-SAT CubeSat. The "
            "benchmark's own test partition entire and unsampled, z-scored by the StandardScaler "
            "published in this student's weights.json -- the same transform it was distilled "
            "under, not one re-fitted here."),
        "input": {"shape": [1, len(mean)], "dtype": "float32", "preprocessing": [],
                  "layout": "samples[i] is one segment's 19 features, z-scored, in the order below"},
        "feature_names": list(datasets.OPSSAT_FEATURES),
        "classes": {"0": "nominal", "1": "anomalous"},
        "samples": z.tolist(),
        "labels": y.tolist(),
        "expected": {
            "graph": "model.onnx",
            "minority_class_f1": f1,
            "all_positive_f1": all_pos,
            "note": (f"Scored on rare-class F1, which is the metric this student is published with; "
                     f"accuracy would read about {float((pred == y).mean()):.2f} on a partition "
                     f"that is {float(np.mean(y == 1)) * 100:.0f} percent anomalous and would say "
                     f"very little. {f1:.4f} against an all-positive baseline of {all_pos:.4f} is "
                     f"{ratio:.1f}x. The whole published test partition, so this reproduces the "
                     f"registry's recorded student figure rather than resampling it."),
        },
    }


def build_finance_student(rng: np.random.Generator) -> dict:
    """The finance teacher's own 8192 rows, z-scored by the published scaler.

    Deliberately the SAME rows the gradient-boosting teacher's sample ships, so the two figures on
    the page describe one row set and are comparable with each other.

    This one does NOT reproduce the registry's recorded 0.0178, and the note says so. That figure is
    measured on the full 1,523,504-row test split at AMLworld's real prevalence of about 1 in 981.
    These 8192 rows are stratified to contain positives -- an unstratified draw would be all-negative
    and every metric on it vacuous -- which lifts prevalence to 1.8 percent and rare-class F1 with
    it. Shipping 0.3337 as though it were the corpus figure would overstate the model 19-fold.
    """
    teacher = json.loads((REPO / "models" / "finance_aml_gbm" / "eval_sample.json").read_text())
    x = np.asarray(teacher["samples"], dtype=float)
    y = np.asarray(teacher["labels"], dtype=int)
    mean, scale = _student_scaler("finance_aml_student")
    z = ((x - mean) / scale).round(6)                     # round BEFORE predicting
    pred = _predict("finance_aml_student", z)
    f1, all_pos, ratio = _f1_over_baseline(y, pred)

    from qsh.models import registry

    corpus = (registry.achieved("finance_aml.student") or {}).get("student_metric")
    corpus_n = (registry.achieved("finance_aml.student") or {}).get("n_eval")

    return {
        "task": "classification",
        "provenance": teacher["provenance"] + (
            " Z-scored here by the StandardScaler published in the student's weights.json -- the "
            "same transform it was distilled under. These are the identical rows the gradient-"
            "boosting teacher's sample ships, so the two numbers on this page describe one row set."),
        "input": {"shape": [1, len(mean)], "dtype": "float32", "preprocessing": [],
                  "layout": "samples[i] is one transaction's 32 engineered features, z-scored"},
        "samples": z.tolist(),
        "labels": y.tolist(),
        "expected": {
            "graph": "model.onnx",
            "minority_class_f1": f1,
            "all_positive_f1": all_pos,
            "note": (
                f"{f1:.4f} on THESE rows, which is not the {corpus:.4f} the registry records for "
                f"this student. That figure is measured on the full {corpus_n:,}-row test split at "
                f"AMLworld's real prevalence of about 1 in 981; these 8192 rows are stratified to "
                f"contain positives, because an unstratified draw of that corpus is all-negative "
                f"and every metric on it is vacuous. Rare-class F1 rises with prevalence, so the "
                f"two differ by about 19x and neither is wrong. What survives the change is the "
                f"ratio to the all-positive baseline: {ratio:.1f}x here against roughly 8.7x on the "
                f"full corpus. Read this number against the {all_pos:.4f} baseline beside it, not "
                f"against the registry's."),
        },
    }

