#  Two decisions apply to all of them.
#
#  ROWS ARE MODEL-READY. The browser's applyPreprocessing() is per-scalar and understands three
#  instructions; it cannot apply a 32-length mean/scale vector or an area resize, and it throws
#  rather than guess. So the transform is applied HERE and the sample ships `preprocessing: []`,
#  which is what the finance teacher's sample already does. The alternative -- teaching the browser
#  vector arithmetic -- would put the students' preprocessing in two places that must agree.
#
#  THE SCALER COMES FROM weights.json, never re-fitted. A StandardScaler fitted here on the test
#  split would be a different transform from the one the student was trained under, and would
#  produce a plausible, wrong number rather than an error. That is the exact trap Round 20 recorded
#  when these students published coefficients without their scaler.


def _student_scaler(model_dir: str) -> tuple[np.ndarray, np.ndarray] | tuple[None, None]:
    """The PUBLISHED mean/scale, ``(None, None)`` if the graph scales itself, else a loud failure.

    Three states, and they must not be collapsed. A student that publishes a scaler needs the caller
    to apply it. A PIPELINE student publishes `mean: null` deliberately, because its ONNX graph owns
    the expansion and the scaler and takes raw features - there is nothing for the caller to do, and
    applying a scaler anyway would z-score twice. A student that publishes neither is a packaging
    bug: the graph would silently accept wrong-scale input and answer confidently.
    """
    w = json.loads((REPO / "models" / model_dir / "weights.json").read_text())
    inp = w.get("input") or {}
    if inp.get("expansion") or (inp.get("mean") is None and inp.get("preprocessing") == []):
        return None, None                       # graph is self-contained; feed it raw
    if inp.get("mean") is None or inp.get("scale") is None:
        raise SystemExit(
            f"{model_dir}/weights.json publishes no scaler and declares no in-graph preprocessing, "
            f"so its ONNX cannot be fed correctly from here. Re-run its training script with "
            f"distil.save_student(..., scaler=...) and republish -- do not guess one.")
    return np.asarray(inp["mean"], dtype=float), np.asarray(inp["scale"], dtype=float)


def _predict(model_dir: str, x: np.ndarray) -> np.ndarray:
    """Argmax of the published student graph. fp32: these students ship no int8 artefact."""
    sess, _ = _session(model_dir, prefer_int8=False)
    out = sess.run(None, {sess.get_inputs()[0].name: x.astype(np.float32)})
    scores = next((o for o in out if getattr(o, "ndim", 0) == 2 and o.shape[1] > 1), out[0])
    return np.asarray(scores).argmax(1)


def declared_metric_expectation(key: str, y, pred) -> dict:
    """The metric the model is PUBLISHED with, added to `expected` so the browser verifies on it.

    The in-run verification re-scores the whole sample and compares against `expected`. It picks the
    strongest metric the sample publishes, so whatever is written here decides what "verification
    PASS" actually asserts.

    Auditing that after the verification step shipped: SIX of nine models published only `accuracy`
    while their declared headline was minority-class F1, AUC, AUC-PR or macro F1. On finance that
    means verifying at a 1.8% positive rate where the majority baseline is 0.9818 and the model
    scores 0.9932 - a model predicting "clean" unconditionally passes with a 1.1pp shortfall. The
    check was weakest exactly where this project's whole metric discipline says it matters most.

    Only metrics computable from hard predictions are emitted here. AUC and AUC-PR need scores; the
    browser HAS them (it runs the graph) but the comparison value is not written yet, and that gap
    is recorded rather than papered over with an accuracy figure standing in for an AUC.
    """
    from qsh.models import metrics
    from qsh.models.registry import get as _get

    y = np.asarray(y).ravel()
    pred = np.asarray(pred).ravel()
    try:
        declared = _get(key).metric.name
    except Exception:
        return {}
    if declared == "minority_class_f1":
        return {"minority_class_f1": float(metrics.minority_class_f1(y, pred))}
    if declared == "macro_f1":
        return {"macro_f1": float(metrics.macro_f1(y, pred))}
    if declared == "accuracy":
        return {}                                   # already written by every caller
    # auc / auc_pr / event_wise_f0_5 / c_index_eur: not derivable from argmax alone.
    return {"declared_metric_not_verifiable": declared}


def _f1_over_baseline(y: np.ndarray, pred: np.ndarray) -> tuple[float, float, float]:
    """Rare-class F1, the F1 of flagging everything, and the ratio between them.

    Rare-class F1 does not survive a change of prevalence, and the ratio to the all-positive
    baseline is the part that can. Whether it does is measured, not assumed: build_finance_student
    states both on the enriched sample and on the whole test window, and says which way they came out.
    """
    from qsh.models import metrics

    f1 = float(metrics.minority_class_f1(y, pred))
    prevalence = float(np.mean(y == 1))
    all_pos = (2 * prevalence) / (1 + prevalence) if prevalence else 0.0
    return f1, all_pos, (f1 / all_pos if all_pos else float("nan"))


def build_medical_student(rng: np.random.Generator) -> dict:
    """BreastMNIST test split at 14x14, the resolution the student was distilled at.

    Reproduces the recorded fidelity exactly: accuracy 0.730769 on all 156 rows.
    """
    import os

    from medmnist import BreastMNIST

    from qsh.ai.cnn_layers import downsample

    root = os.path.join(os.environ["QSH_DATA_ROOT"], "raw", "medmnist")
    ds = BreastMNIST(split="test", download=False, root=root)
    imgs, y = ds.imgs, ds.labels.ravel().astype(int)

    x = imgs.astype(np.float32)[:, None, :, :] / 255.0
    x = (x - 0.5) / 0.5                                  # train/medical_breastmnist.py
    x14 = np.asarray(downsample(x, 14), dtype=float)     # F.interpolate(mode="area"), as distilled
    x14 = x14.round(6)                                   # round BEFORE predicting
    pred = _predict("medical_breastmnist_student", x14)

    return {
        "task": "classification",
        "provenance": _breastmnist_provenance(
            "MedMNIST v2 BreastMNIST ultrasound images: the official test split, all 156.") + (
            " Normalised and area-resized to 14x14 here, which is the resolution this student was "
            "distilled at and the one its encrypted convolution runs on -- the ResNet-18 teacher on "
            "this same page runs at 28x28, so the two are not interchangeable inputs."),
        "input": {"shape": [1, 1, 14, 14], "dtype": "float32", "preprocessing": [],
                  "layout": "samples[i] is one 14x14 image, row-major, already normalised"},
        # MedMNIST BreastMNIST: {0: malignant, 1: "normal, benign"}. onnxInference.ts renders
        # classes[predictedClass], so inverting this list reports the OPPOSITE diagnosis.
        "classes": {"0": "malignant", "1": "normal/benign"},
        "samples": x14.reshape(len(y), -1).tolist(),
        "labels": y.tolist(),
        "expected": {
            "graph": "model.onnx",
            "accuracy": float((pred == y).mean()),
            "majority_baseline": float(max(np.bincount(y)) / len(y)),
            **declared_metric_expectation("medical_fl.student", y, pred),
            "note": ("The whole official test split, and the same rows the registry's recorded "
                     "student accuracy was measured on, so this reproduces that figure rather than "
                     "resampling it."),
        },
    }


def build_opssat_student(rng: np.random.Generator) -> dict:
    """OPS-SAT-AD test partition, z-scored by the published scaler.

    Reproduces the recorded fidelity exactly: minority-class F1 0.864865 on all 529 segments.
    """
    from qsh.models import datasets

    x, y = datasets.opssat_ad("test")
    y = np.asarray(y, dtype=int)
    # The student is now a Pipeline whose ONNX graph owns its quadratic expansion AND its scaler,
    # so it takes RAW features and there is nothing for the caller to pre-apply. Reading
    # `input.mean` here would fail: a pipeline student publishes it as null precisely because
    # scaling is no longer the consumer's job. Fall back to the published scaler only for a bare
    # student, which is still the shape every other use case ships.
    mean, _scale = _student_scaler("satellite_opssat_student")
    if mean is None:
        z = np.asarray(x, dtype=float).round(6)
        layout = "samples[i] is one segment's 19 RAW features, in the order below"
        prep_note = ("the published ONNX graph applies the quadratic expansion and the z-scoring "
                     "itself, so these are raw feature values and the caller applies nothing")
    else:
        z = ((np.asarray(x, dtype=float) - mean) / _scale).round(6)   # round BEFORE predicting
        layout = "samples[i] is one segment's 19 features, z-scored, in the order below"
        prep_note = ("z-scored by the StandardScaler published in this student's weights.json -- "
                     "the same transform it was distilled under, not one re-fitted here")
    pred = _predict("satellite_opssat_student", z)
    f1, all_pos, ratio = _f1_over_baseline(y, pred)

    return {
        "task": "classification",
        "provenance": (
            "OPS-SAT-AD (Ruszczak et al., Scientific Data 12, 2025; Zenodo "
            "10.5281/zenodo.12588359, CC BY 4.0). Real telemetry from ESA's OPS-SAT CubeSat. The "
            "benchmark's own test partition entire and unsampled, " + prep_note + "."),
        "input": {"shape": [1, int(z.shape[1])], "dtype": "float32", "preprocessing": [],
                  "layout": layout},
        "feature_names": list(datasets.OPSSAT_FEATURES),
        "classes": {"0": "nominal", "1": "anomalous"},
        "samples": z.tolist(),
        "labels": y.tolist(),
        "expected": {
            "graph": "model.onnx",
            "minority_class_f1": f1,
            "all_positive_f1": all_pos,
            "note": (f"Scored on rare-class F1, which is the metric this student is published with; "
                     f"accuracy would read about {float((pred == y).mean()):.2f} on a partition "
                     f"that is {float(np.mean(y == 1)) * 100:.0f} percent anomalous and would say "
                     f"very little. {f1:.4f} against an all-positive baseline of {all_pos:.4f} is "
                     f"{ratio:.1f}x. The whole published test partition, so this reproduces the "
                     f"registry's recorded student figure rather than resampling it."),
        },
    }


def build_finance_student(rng: np.random.Generator) -> dict:
    """The finance teacher's own 8192 rows, z-scored by the published scaler.

    Deliberately the SAME rows the gradient-boosting teacher's sample ships, so the two figures on
    the page describe one row set and are comparable with each other. Build the teacher's sample
    first: this reads it.

    This one does NOT reproduce the registry's recorded student figure, and the note says by how much
    and why. That figure is measured on the whole test window at its real prevalence; these rows are
    drawn from the same window but enriched to contain positives. The note used to carry its numbers
    as literals ("about 19x", "roughly 8.7x"), and after a retrain they no longer described the
    figures printed beside them: 0.3761 against 0.0614 is 6.1x, not 19x. They are computed now.
    """
    teacher = json.loads((REPO / "models" / "finance_aml_gbm" / "eval_sample.json").read_text())
    x = np.asarray(teacher["samples"], dtype=float)
    y = np.asarray(teacher["labels"], dtype=int)
    mean, scale = _student_scaler("finance_aml_student")
    z = ((x - mean) / scale).round(6)                     # round BEFORE predicting
    pred = _predict("finance_aml_student", z)
    f1, all_pos, ratio = _f1_over_baseline(y, pred)

    from qsh.models import registry

    rec = registry.achieved("finance_aml.student") or {}
    corpus, corpus_n = float(rec["student_metric"]), int(rec["n_eval"])
    # The teacher's record carries the test window's positive rate as the AUPRC baseline, which is
    # what a coin-flip detector scores and so exactly the window's prevalence.
    rate = float((registry.achieved("finance_aml.gbm") or {})["auprc_baseline"])
    corpus_all_pos = 2 * rate / (1 + rate)
    corpus_ratio = corpus / corpus_all_pos
    here = float(np.mean(y == 1))
    teacher_here = float(teacher["expected"]["minority_class_f1"])
    teacher_window = float(rec["teacher_metric"])
    # Said when it happens, because the page prints the two side by side.
    inverted = (f1 > teacher_here) != (corpus > teacher_window)
    order = (f" On these rows the student scores {'above' if f1 > teacher_here else 'below'} its "
             f"teacher ({f1:.4f} against {teacher_here:.4f}) and over the whole window "
             f"{'above' if corpus > teacher_window else 'below'} it ({corpus:.4f} against "
             f"{teacher_window:.4f}): enrichment rewards whichever model flags more, so the order "
             "of the two on this sample is not a ranking." if inverted else "")
    survives = abs(ratio - corpus_ratio) <= 0.25 * corpus_ratio
    tail = (f"What survives the change is the ratio to the all-positive baseline: {ratio:.1f}x here "
            f"against {corpus_ratio:.1f}x on the whole window."
            if survives else
            f"Not even the ratio to the all-positive baseline survives it: {ratio:.1f}x here against "
            f"{corpus_ratio:.1f}x on the whole window, so this sample checks that the browser "
            "reproduces the graph, not how good the student is.")

    return {
        "task": "classification",
        "provenance": teacher["provenance"] + (
            " Z-scored here by the StandardScaler published in the student's weights.json -- the "
            "same transform it was distilled under. These are the identical rows the gradient-"
            "boosting teacher's sample ships, so the two numbers on this page describe one row set."),
        "input": {"shape": [1, len(mean)], "dtype": "float32", "preprocessing": [],
                  "layout": "samples[i] is one transaction's 32 engineered features, z-scored"},
        "samples": z.tolist(),
        "labels": y.tolist(),
        "expected": {
            "graph": "model.onnx",
            "minority_class_f1": f1,
            "all_positive_f1": all_pos,
            "note": (
                f"{f1:.4f} on THESE rows, which is not the {corpus:.4f} the registry records for "
                f"this student. That figure is measured on all {corpus_n:,} rows of the test window "
                f"at its real prevalence of {rate:.2%}, about 1 in {1 / rate:.0f}; these {len(y):,} "
                f"rows come from the same window but are enriched to {here:.1%} laundering, because "
                f"an unenriched draw of this size would hold about {len(y) * rate:.0f} positives and "
                f"every metric on it would be noise. Rare-class F1 rises with prevalence, so the two "
                f"differ by {f1 / corpus:.1f}x and neither is wrong. " + tail + order
                + f" Read this number against the {all_pos:.4f} baseline beside it, not against the "
                "registry's."),
        },
    }


