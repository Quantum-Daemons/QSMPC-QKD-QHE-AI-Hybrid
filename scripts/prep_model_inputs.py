import json
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))
sys.path.insert(0, str(REPO / "scripts"))

OUT_ROOT = REPO / "web" / "public" / "data"

#: How many rows each use case ships, chosen per model rather than globally, because the right
#: answer depends entirely on how big one row is.
#:
#:  * medical    -- the ENTIRE official BreastMNIST test split. 156 x 28 x 28 uint8 is ~0.4 MB raw
#:                  and digits compress well, so the browser can reproduce the model's PUBLISHED
#:                  test metric exactly rather than a subsample of it. That is a much stronger
#:                  claim and it costs almost nothing.
#:  * finance    -- 8192 rows of 32 floats. A 1-in-981 positive rate needs volume before an
#:                  accuracy figure means anything, and this narrows the 95% interval to ~+/-0.6pp
#:                  against ~+/-2.6pp at 512.
#:  * satellite  -- 128 windows. One window is 250 x 6 = 1500 floats, still the heaviest row here.
#:
#: The full training corpora are deliberately NOT shipped: AMLworld is 475 MB, ESA-ADB is 3.6 GB,
#: and neither may be redistributed (see DATA_LICENSES.md). A browser does not need the training
#: corpus to verify a model -- it needs a held-out sample large enough to be worth believing.
N_SAMPLES = {"medical_fl": None, "finance_aml": 8192, "satellite_comms": 128,
             # The whole OPS-SAT test split: 529 rows of 19 floats is ~200 KB, so
             # the browser can reproduce the published-split number exactly rather
             # than a subsample of it.
             "satellite_opssat": None,
             # Both entire held-out splits. Telecom's corpus is generated by this repository, so
             # there is no licence question and no reason to subsample; medical's is the official
             # BreastMNIST test split, the same one medical_fl.resnet18 ships, so the two teachers
             # are verified on identical rows and the comparison between them is like for like.
             "telecom_ids": None, "medical_resnet50": None,
             # 5G-NIDD, and the one case here where "the whole test split" is not an option: it is
             # 303,973 rows x 47 features, roughly 120 MB against a 4.5 MB largest-committed-sample
             # today. 16,384 rows keeps the interval on a 9-class macro F1 tight while landing in
             # the same size class as the finance sample. See build_telecom_nidd for why the draw is
             # NOT proportional and what that costs.
             "telecom_nidd": 16384}

#: Minimum rows per class in the 5G-NIDD sample, regardless of prevalence.
#:
#: A strictly proportional 16,384-row draw gives ICMPFlood about 15 rows, at which point its
#: per-class F1 moves in steps of 1/15 and the browser would be "verifying" noise. The test
#: partition holds 289 ICMPFlood rows, so a floor of 200 is satisfiable for every class. The cost is
#: real and is stated in the payload rather than hidden: the sample is not the corpus distribution,
#: so its macro F1 is not the corpus macro F1. `build_finance_student` makes the same trade for the
#: same reason and states its own prevalence gap, computed, rather than papering over it.
NIDD_MIN_PER_CLASS = 200


def _session(model_dir: str, prefer_int8: bool = True):
    """The published graph, preferring the int8 the browser tier actually downloads."""
    import onnxruntime as ort

    base = REPO / "models" / model_dir / "onnx"
    for name in (["model_int8.onnx", "model.onnx"] if prefer_int8 else ["model.onnx"]):
        p = base / name
        if p.exists():
            return ort.InferenceSession(str(p), providers=["CPUExecutionProvider"]), name
    raise FileNotFoundError(f"no ONNX graph under {base}")



def _apply_preprocessing_step(x: np.ndarray, step: str) -> np.ndarray:
    """Apply one `input.preprocessing` instruction, the same strings the browser parses.

    Kept as a tiny interpreter rather than hardcoded arithmetic so a generator and the browser
    cannot drift: if a step is added here it has to be added there, and an unknown step raises
    instead of being skipped.
    """
    s = step.strip().lower()
    if s.startswith("divide by "):
        return x / float(s.removeprefix("divide by "))
    if s.startswith("subtract "):
        return x - float(s.removeprefix("subtract "))
    if s.startswith("multiply by "):
        return x * float(s.removeprefix("multiply by "))
    raise ValueError(f"unknown preprocessing step {step!r} - add it here and in onnxInference.ts")


def _invalidate_pin_if_published(key: str) -> None:
    """Demote a published model's `hf_revision` when its eval sample is rewritten.

    THE GAP THIS CLOSES. `models/train.py` already demotes the pin to
    `hf_revision_invalidated_by_retrain` when a model is RETRAINED, on the reasoning that a pin
    pointing at weights nobody can reproduce is worse than no pin. Regenerating an EVALUATION SAMPLE
    is the same hazard and had no such hook - and the sample is exactly what the browser fetches
    `<repo>/resolve/<sha>/eval_sample.json` to get.

    So after the Round 25 label-leak fix the local sample carried 164 positives while Hugging Face
    still served 149 at the pinned sha, with `hour_of_day` negatives on 3 distinct values against 22
    for positives - the leak signature. Every local check passed, the pin looked valid, and the
    browser read the contaminated sample. Nothing anywhere said the two had diverged.

    A warning is not enough here: the pin is what makes the model reachable, so leaving it pointing
    at a sample that no longer matches the repository is the silent-desync case. Demoting it makes
    the model drop out of the browser dropdown until it is republished, which is loud and correct.
    """
    from qsh.models import registry

    metrics_path = registry.METRICS_PATH
    try:
        current = json.loads(metrics_path.read_text())
    except (FileNotFoundError, json.JSONDecodeError):
        return
    entry = current.get(key) or {}
    rev = entry.get("hf_revision")
    if not rev:
        return                       # not published, or already invalidated
    entry.pop("hf_revision", None)
    entry["hf_revision_invalidated_by_retrain"] = rev
    current[key] = entry
    metrics_path.write_text(json.dumps(current, indent=2, sort_keys=True) + "\n")
    print(f"    PIN INVALIDATED for {key}: {rev[:12]} -> hf_revision_invalidated_by_retrain. "
          f"The published sample no longer matches this one, so the model is withheld from the "
          f"browser until `scripts/publish_hf.py --key {key} --public` re-pins it.")


#: One-vs-rest rank-AUC at or above which a single feature is reported as doing the model's job.
#: Named rather than inline because a caller that records the result has to publish the threshold
#: the number was measured at, and two copies of 0.90 would be one copy too many.
LEAK_AUC_THRESHOLD = 0.90


def _warn_single_feature_leak(usecase: str, payload: dict) -> list[tuple[float, str, int]]:
    """Warn when ONE feature separates the classes well enough to be doing the model's job.

    Returns the flagged ``(auc, feature_name, class_index)`` triples, highest first, so a caller can
    RECORD what was found rather than only print it. Every existing caller ignores the return value
    and is unaffected. `scripts/train/telecom_nidd.py` needs the list as data: on 5G-NIDD the check
    fires on roughly half the features, legitimately, and the published feature_spec has to state
    that count and distinguish it from the row identifiers it does NOT fire on. A count asserted in
    prose and measured nowhere is the drift this repository has a gate for.

    This exists because one did. The finance sample was built from `nrows=400_000` of a time-sorted
    corpus, which left `hour_of_day >= 3` implying laundering at 100% precision - a leak created by
    the sampling, absent from the source, and worth 13.8% of the figure the browser verified against.
    Nothing caught it: the payload was well-formed, the browser re-scored it and matched, and every
    gate was green. A reproducible number measured on contaminated rows is still contaminated.

    Two bugs of my own are recorded here because both produced confident nonsense:

      1. The first version asked whether positives occupied values no negative took. Sound for a
         low-cardinality index like an hour, meaningless for a continuous float - it flagged
         `amount_paid_log` at 99.7% purely because distinct doubles rarely collide.
      2. The second used a binary rank-AUC formula on multi-class labels. `y == 1` picked one class
         out of eight while the ranks spanned every row, so the normaliser was wrong and it printed
         AUC 5.1292 for telecom. An impossible number is at least loud; a plausible wrong one would
         not have been.

    Now ONE-VS-REST: for each column and each class, rank-AUC of that class against all others.
    Binary data is the two-class case of the same computation, so there is one code path.

    A WARNING, not a hard failure. A legitimately dominant feature exists in some corpora - a QKD
    attack simulator is built so that its signatures ARE separable - and a build that refuses to run
    is worse than one that reports what it found and lets a human judge.
    """
    samples, labels = payload.get("samples"), payload.get("labels")
    names = payload.get("feature_names") or []
    if not samples or not labels:
        return []
    y = np.asarray(labels, dtype=int)
    classes = np.unique(y)
    if classes.size < 2:
        return []
    x = np.asarray(samples, dtype=float)
    if x.ndim != 2 or x.shape[1] != len(names):
        return []                                 # image/sequence payloads: not a flat feature space

    flagged: list[tuple[float, str, int]] = []
    for j, nm in enumerate(names):
        col = x[:, j]
        r = np.argsort(np.argsort(col, kind="mergesort"), kind="mergesort").astype(float) + 1.0
        best_auc, best_cls = 0.0, int(classes[0])
        for c in classes:
            m = y == c
            n_pos, n_neg = int(m.sum()), int((~m).sum())
            if not n_pos or not n_neg:
                continue
            auc = (r[m].sum() - n_pos * (n_pos + 1) / 2.0) / (n_pos * n_neg)
            auc = max(auc, 1.0 - auc)             # symmetric: a perfectly inverted feature is as telling
            if auc > best_auc:
                best_auc, best_cls = auc, int(c)
        if best_auc >= LEAK_AUC_THRESHOLD:
            flagged.append((best_auc, nm, best_cls))
    flagged.sort(reverse=True)
    for auc, nm, c in flagged:
        label = (payload.get("class_names") or [])
        cname = label[c] if c < len(label) else str(c)
        print(f"    LEAK WARNING [{usecase}]: '{nm}' alone separates class '{cname}' from the rest "
              f"at AUC {auc:.4f}. A label recoverable from one feature measures the sampling, not "
              f"the model - check how the rows were drawn before publishing this.")
    return flagged

def _write(usecase: str, payload: dict) -> Path:
    """Write beside the model, not into the web bundle.

    The evaluation sample belongs in the model's own HF repo at the same pinned commit: the sample
    and the weights it evaluates then travel together and cannot drift apart, the demo image stops
    carrying 1.6 MB it does not need, and HF's CDN serves the bytes instead of a 12 GB VPS. That
    last point is what makes a larger sample affordable -- 8192 AMLworld rows narrow the 95%
    interval on accuracy from about +/-2.6pp to +/-0.6pp, and none of it touches this repository.
    """
    from qsh.models import registry

    key = _MODEL_KEY[usecase]
    split = registry.get(key).eval_split
    if not split:
        raise SystemExit(f"{key} declares no eval_split in the registry. Say which split this sample "
                         "is drawn from before publishing it: the run log prints that sentence.")
    # Written from the registry, after the provenance where a reader looks for where the rows came
    # from, so the file and the page state the same split.
    ordered: dict = {}
    for k, v in payload.items():
        if k == "split":
            continue
        ordered[k] = v
        if k == "provenance":
            ordered["split"] = split
    payload = ordered
    out = REPO / registry.ARTIFACT_DIRS[key] / "eval_sample.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    _warn_single_feature_leak(usecase, payload)
    _invalidate_pin_if_published(key)
    out.write_text(json.dumps(payload, indent=1) + "\n")
    size = out.stat().st_size
    print(f"  wrote {out.relative_to(REPO)}  ({size/1024:.0f} KB)")
    exp = payload["expected"]
    if "minority_class_f1" in exp:
        # Checked first: three of the four students are published with THIS metric, and a payload
        # carrying both would otherwise be summarised by the more flattering one.
        f1, base = exp["minority_class_f1"], exp.get("all_positive_f1") or 0.0
        ratio = f" ({f1 / base:.1f}x)" if base else ""
        print(f"    expected rare-class F1 on these rows: {f1:.4f} "
              f"(all-positive baseline {base:.4f}{ratio})")
    elif "accuracy" in exp:
        acc, base = exp["accuracy"], exp["majority_baseline"]
        print(f"    expected accuracy on these rows: {acc:.4f} "
              f"(majority-class baseline {base:.4f})")
        if acc <= base:
            print("    NOTE: at or below the majority baseline. This model does not beat guessing "
                  "the commonest label on these rows, and the page will say so rather than not.")
    else:
        print(f"    expected forecast MAE on these windows: {exp['mae']:.4f} "
              f"(persistence baseline {exp['persistence_mae']:.4f})")
    return out


