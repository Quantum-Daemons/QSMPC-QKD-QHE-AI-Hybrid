"""Export the SP 800-90B section 4.4 cutoffs so the browser can be held to them.

WHY THIS EXISTS

`src/qsh/qrng/health.py` computes both cutoffs with `scipy.stats.binom`. The browser cannot ship
scipy, so `web/src/lib/clientQRNG.ts` reimplements both by summing the binomial pmf in log space.
Two implementations of one quantity, in two languages, with no artefact holding them together.

They diverged. `adaptiveProportionCutoff` returned `1 + c` where the loop already held the answer -
the `1 +` was transcribed from the Python, where it is correct because `binom.isf` returns one BELOW
the cutoff. The result was a uniform off-by-one at every entropy: 991/990, 793/792, 626/625, 590/589,
325/324, 106/105, always in the permissive direction, because a higher cutoff fails fewer windows.
Since the demo is client-side only, the browser value is the one a visitor is shown and the one
`healthPassed` is computed from.

WHY A SPOT CHECK WAS NOT ENOUGH, which is the point of the grid

`web/scripts/check_qkd.mjs` already asserted `repetitionCountCutoff(2.0, 2^-20) === 11` - SP 800-90B
section 4.4.1's own worked example, correct, and on the SIBLING function. One point on one of two
functions cannot see a uniform offset in the other. So this exports a GRID, and the check compares
every entry.

Same shape as `scripts/export_combiner_vectors.py`: the Python side is the authority, the artefact is
committed, and `scripts/ci_local.sh` regenerates it and fails on a diff.
"""

from __future__ import annotations

import json
from pathlib import Path

from qsh.qrng.health import (
    ADAPTIVE_PROPORTION_W,
    HEALTH_ALPHA,
    adaptive_proportion_cutoff,
    repetition_count_cutoff,
)

OUT = Path(__file__).resolve().parents[1] / "web" / "scripts" / "vectors" / "qrng_cutoffs.json"

#: Spans the range the health suite can actually see. The low end matters most: a collapsing source
#: has LOW min-entropy, so that is where the cutoff decides whether a failing source is reported as
#: failing, and it is also where the off-by-one was largest in absolute terms (991 against 990).
GRID = [0.05, 0.1, 0.25, 0.5, 0.75, 0.9, 1.0, 1.5, 2.0, 3.0, 4.0, 6.0, 8.0]


def main() -> None:
    payload = {
        "_": (
            "SP 800-90B section 4.4 cutoffs, computed by src/qsh/qrng/health.py and regenerated by "
            "scripts/export_qrng_cutoffs.py. The browser reimplements both without scipy, and a "
            "SINGLE spot check cannot see a uniform offset - which is exactly what shipped: "
            "adaptiveProportionCutoff returned c+1 at EVERY entropy, in the permissive direction."
        ),
        "w": ADAPTIVE_PROPORTION_W,
        "alpha": HEALTH_ALPHA,
        "adaptive_proportion": {f"{h:g}": adaptive_proportion_cutoff(h) for h in GRID},
        "repetition_count": {f"{h:g}": repetition_count_cutoff(h) for h in GRID},
    }
    OUT.write_text(json.dumps(payload, indent=1) + "\n")
    print(f"wrote {OUT.relative_to(OUT.parents[3])} ({len(GRID)} entropies, W={ADAPTIVE_PROPORTION_W})")


if __name__ == "__main__":
    main()
