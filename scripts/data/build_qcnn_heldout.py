#!/usr/bin/env python3
"""Ship each trained QCNN's held-out rows, so the page re-scores the circuit in the tab (Round 86).

WHY THIS EXISTS

The pages printed the QCNN's held-out figures - accuracy, macro F1 or minority-class F1 - from the weights file, and said so:
"recorded at training time ... not re-scored in this tab". The CKKS and ONNX tiers are re-scored on their held-out rows; the
circuit was the one model whose headline a visitor could not reproduce (audit of 2026-11-08, lead P3-O1). This writes, per use
case, the rows of the trainer's own test split in the units the browser's `qcnnInferTrained` takes (raw), with their labels, so
the tab can run the trained circuit over every one of them and compute the same metric the trainer recorded.

THE ROWS ARE THE TRAINER'S SPLIT, NOT A SECOND IMPLEMENTATION OF IT

`load()` and `shuffled_split()` come from `scripts/train/qcnn_variational.py`, the seed from the artifact's own `training.seed`,
and a file is written only when, for every artifact that reads it:
  - the artifact's `feature_mean` and `feature_std` are the moments of the training rows this split yields,
  - its `feature_names` are the loader's columns and its `n_test` the split's test-row count,
  - and the trainer's `circuit()`, run on the rows written here, reproduces every test metric the artifact records.

The values are written as the loader returns them, not rounded: a rounded feature can move a row across a decision boundary,
which is the defect a re-score exists to expose rather than introduce.

    .venv/bin/python scripts/data/build_qcnn_heldout.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import torch
from sklearn.metrics import f1_score

REPO = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(REPO / "scripts" / "train"), str(REPO / "src")]

import qcnn_variational as q  # noqa: E402

PUBLIC = REPO / "web" / "public" / "data"

#: (the trainer's use case, the served data directory, the weights files in it that read these rows)
TARGETS = (
    ("finance", "finance", ("qcnn_weights.json",)),
    ("medical", "medical", ("qcnn_weights.json",)),
    ("telecom", "telecom", ("qcnn_weights.json", "qcnn_weights_q7.json")),
)

#: What each file is released under, from DATA_LICENSES.md's entries for the same rows.
LICENCES = {
    "finance": ("CC-BY-SA-4.0", "https://creativecommons.org/licenses/by-sa/4.0/",
                "E. A. Lopez-Rojas, A. Elmir and S. Axelsson, 'PaySim: A financial mobile money simulator for fraud detection', "
                "EMSS 2016; Kaggle ealaxi/paysim1. Rows from this repository's data/finance/paysim_sample.tsv."),
    "medical": ("CC-BY-4.0", "https://creativecommons.org/licenses/by/4.0/",
                "W. Wolberg, O. Mangasarian, N. Street and W. Street, 'Breast Cancer Wisconsin (Diagnostic)', UCI Machine "
                "Learning Repository (1993), doi:10.24432/C5DW2B."),
    "telecom": ("Apache-2.0", "https://www.apache.org/licenses/LICENSE-2.0",
                "Generated by this repository's qsh.qml_ids.attacks; no third-party data."),
}


def _metrics(w: dict, y: np.ndarray, pred: np.ndarray) -> dict:
    multiclass = bool((w.get("readout") or {}).get("readout_qubits"))
    return {"test_accuracy": round(float((pred == y).mean()), 6),
            "test_macro_f1": round(float(f1_score(y, pred, average="macro", zero_division=0)), 6) if multiclass else None,
            "test_minority_f1": None if multiclass else round(float(f1_score(y, pred, zero_division=0)), 6)}


def _trainer_predictions(w: dict, x_raw: np.ndarray) -> np.ndarray:
    """The trainer's own circuit on raw rows: standardise with the artifact's moments, c * tanh, zero pad, circuit, scale, bias."""
    mean, std = np.asarray(w["feature_mean"]), np.asarray(w["feature_std"])
    c = float(w.get("encoding_scale", 1.0))
    nq, layers = int(w["n_qubits"]), int(w["layers"])
    ro = int((w.get("readout") or {}).get("readout_qubits", 0) or 0)
    x = c * np.tanh((x_raw - mean) / np.where(std == 0, 1.0, std))
    if x.shape[1] < nq:
        x = np.hstack([x, np.zeros((len(x), nq - x.shape[1]))])
    with torch.no_grad():
        z = q.circuit(torch.tensor(x, dtype=torch.float32), torch.tensor(w["theta"], dtype=torch.float32), nq,
                      readout_qubits=ro, layers=layers, arch=str((w.get("circuit") or {}).get("name", "tree")))
        logits = z * torch.tensor(w["scale"], dtype=torch.float32) + torch.tensor(w["bias"], dtype=torch.float32)
        return (logits.argmax(1) if ro else (logits > 0)).int().numpy()


def build(usecase: str, data_dir: str, files: tuple[str, ...], *, check: bool = False) -> bool:
    """Write (or, with `check`, compare) one use case's file; True when the file on disk is what this produces."""
    X, y, names, provenance = q.load(usecase)
    weights = {f: json.loads((PUBLIC / data_dir / f).read_text()) for f in files}
    seeds = {int(w["training"]["seed"]) for w in weights.values()}
    if len(seeds) != 1:
        raise SystemExit(f"{usecase}: the artifacts were split with different seeds {sorted(seeds)}; one file cannot serve both")
    seed = seeds.pop()
    perm, cut, vcut = q.shuffled_split(len(y), seed)
    Xp, yp = X[perm], y[perm]
    mu, sd = Xp[:cut].mean(0), Xp[:cut].std(0)
    x_te, y_te = Xp[vcut:], yp[vcut:].astype(int)
    for f, w in weights.items():
        where = f"{data_dir}/{f}"
        if list(w["feature_names"]) != list(names):
            raise SystemExit(f"{where}: feature names {w['feature_names']} are not the loader's {names}")
        if int(w["n_test"]) != len(y_te):
            raise SystemExit(f"{where}: n_test {w['n_test']}, the split gives {len(y_te)}")
        if not (np.allclose(w["feature_mean"], mu, rtol=1e-12, atol=0) and np.allclose(w["feature_std"], np.where(sd == 0, 1.0, sd), rtol=1e-12, atol=0)):
            raise SystemExit(f"{where}: its feature moments are not this split's training rows'; the rows would be another split")
        got = _metrics(w, y_te, _trainer_predictions(w, x_te))
        want = {k: w.get(k) for k in got}
        if got != want:
            raise SystemExit(f"{where}: the trainer's circuit on these rows gives {got}; the artifact records {want}")
        print(f"  {where}: {len(y_te)} rows reproduce {got}")
    lic, url, credit = LICENCES[usecase]
    out = PUBLIC / data_dir / "qcnn_heldout.json"
    text = json.dumps({
        "usecase": usecase,
        "reads": [f"{data_dir}/{f}" for f in files],
        "feature_names": list(names),
        "input_space": "raw",
        "class_names": weights[files[0]].get("class_names"),
        "split": (f"the test rows of scripts/train/qcnn_variational.py's split: shuffled with seed {seed}, then the last 15 percent "
                  f"({len(y_te)} of {len(y)}); the circuit never trained or chose a checkpoint on them"),
        "rows": [[float(v) for v in r] for r in x_te],
        "labels": [int(v) for v in y_te],
        "provenance": provenance,
        "licence": lic, "licence_url": url, "attribution": credit,
        "modifications": (f"{len(names)} of the corpus's columns, as the QCNN reads them, in their original units; only the test rows of "
                          "the split above, in that split's order. Values are unrounded."),
    }, separators=(",", ":")) + "\n"
    if check:
        same = out.exists() and out.read_text() == text
        print(f"  {out.relative_to(REPO)}: {'as built' if same else 'DIFFERS from what this script builds'}")
        return same
    out.write_text(text)
    print(f"  wrote {out.relative_to(REPO)} ({out.stat().st_size // 1024} KB)")
    return True


def main() -> int:
    import argparse

    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="compare the files on disk with what would be written; write nothing")
    args = ap.parse_args()
    torch.set_num_threads(1)
    ok = all([build(usecase, data_dir, files, check=args.check) for usecase, data_dir, files in TARGETS])
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
