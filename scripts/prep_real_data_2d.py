#!/usr/bin/env python3
"""Bundle a small, redistributable 2D slice of REAL data per use case, for the plot that sits
next to the private-inference result.

The point of this file is that a score plotted alone says how well the model separated the classes
and nothing about whether the classes are separable. A reader cannot tell a good model on easy data
from a mediocre model on hard data. Drawing the real corpus underneath the model's own decisions
answers that, and it is the only way to show a visitor what the encrypted path is actually up
against.

LICENCE IS THE BINDING CONSTRAINT, not size. Every slice here has to be redistributable inside a
public web bundle, which is a stricter test than "publicly downloadable" and knocks out most of the
obvious candidates. What each use case can and cannot do, checked 2026-08-10:

  satellite  OPS-SAT-AD, CC-BY-4.0. Redistributable, AND it is the corpus the published OPS-SAT
             models train on; the overlay is its test partition, which they were not fitted on. The
             page's anomaly demo used to score SMAP/MSL, for which no source grants a data licence
             (the Telemanom LICENSE is a Caltech copyright covering its software, and JPL is
             operated by Caltech, so 17 U.S.C. 105 does not reach it); since Round 84 it scores
             OPS-SAT-AD segments too (`scripts/data/build_heldout_payloads.py`).
  medical    (checked 2026-08-10; superseded 2026-10-26) BreastMNIST/BUSI was judged unusable here
             because the BUSI CC BY attaches to the article, not the data. Since 2026-10-26 this
             project redistributes BreastMNIST on MedMNIST's CC BY 4.0, by recorded decision (the
             BUSI authors state no licence; see the registry and DATA_LICENSES.md). This slice still
             uses WDBC (CC-BY-4.0, already bundled), labelled as a DIFFERENT COHORT AND MODALITY,
             because it is: cell-nucleus morphometry, not ultrasound. Overlaying it on the same axes
             would be a lie.
  genomics   one point per variant of the score: gnomAD genome allele frequencies (CC0), as Ensembl's
             REST variation endpoint lists them, in two gnomAD groups. Not the page's genotypes:
             those are 30 1000 Genomes individuals in the browser payload, which carry no licence
             instrument (IGSR) and are shipped under the cell budget of DATA_LICENSES.md section 4;
             the overlay draws a population-scale frequency per variant, which that slice cannot.
  finance    AMLworld is CDLA-Sharing-1.0. Usable, but share-alike propagates to the bundled slice.
  telecom    the corpus is generated by this repository, so there is no third party to ask - and no
             licence is granted for it either (the registry's DS_QKD_ATTACK_SYNTH), which the
             payload says rather than implying one. Since Round 84 it draws only the 600 rows held
             out from the published telecom models, not the 3,200-row corpus a QCNN trains on.

THE LICENCE TRAVELS WHOLE (Round 84). A name is not what CC BY 4.0 (s.3(a)(1)) or CDLA-Sharing-1.0
(s.3.1(b), s.3.3) ask of shared data: they ask for a link to the licence and a note of the changes.
Every payload carries `licence_url` and `modifications`, and the overlay renders both.

`corpus_is_synthetic` is carried per payload because the caption used to hardcode the word
"real" for every use case, and TWO of the five are not: AMLworld is synthetic by IBM's own
statement (a multi-agent simulator) and the telecom corpus is generated here. The finance page
had been saying "8192 real points" about simulator output long before telecom made it obvious.

Regenerate:  .venv/bin/python scripts/prep_real_data_2d.py
"""
