#!/usr/bin/env python3
"""Bundle a small, redistributable 2D slice of REAL data per use case, for the plot that sits
next to the private-inference result.

The point of this file is that a score plotted alone says how well the model separated the classes
and nothing about whether the classes are separable. A reader cannot tell a good model on easy data
from a mediocre model on hard data. Drawing the real corpus underneath the model's own decisions
answers that, and it is the only way to show a visitor what the encrypted path is actually up
against.

LICENCE IS THE BINDING CONSTRAINT, not size. Every slice here has to be redistributable inside a
public web bundle, which is a stricter test than "publicly downloadable" and knocks out most of the
obvious candidates. What each use case can and cannot do, checked 2026-08-10:

  satellite  OPS-SAT-AD, CC-BY-4.0. Redistributable, AND it is the corpus the shipped model is
             actually trained on - so this is a genuine train-vs-inference comparison rather than a
             lookalike. Note the page currently bundles SMAP/MSL for its anomaly demo, which is NOT
             redistributable: 17 U.S.C. 105 removes US copyright domestically and is not a grant,
             and it is territorial. The redistributable corpus was not the one being shipped.
  medical    BreastMNIST/BUSI CANNOT be used - the CC BY there attaches to the article, not the
             data, and the host asks only to be cited. WDBC (CC-BY-4.0, already bundled) is used
             instead and is labelled as a DIFFERENT COHORT AND MODALITY, because it is: cell-nucleus
             morphometry, not ultrasound. Overlaying it on the same axes would be a lie.
  genomics   1000 Genomes carries no blanket grant (IGSR says so itself), so the training corpus
             cannot ship. gnomAD v4.1 allele frequencies are CC0 and stand in as a reference
             population - again a substitute, not the training data, and labelled as one.
  finance    AMLworld is CDLA-Sharing-1.0. Usable, but share-alike propagates to the bundled slice.
  telecom    the corpus is generated by this repository, so there is no third party to ask.

Regenerate:  .venv/bin/python scripts/prep_real_data_2d.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[1]
WEB = REPO / "web" / "public" / "data"


def _round(x: float, sig: int = 4) -> float:
    """Trim float noise so the bundle stays small and diffs stay readable."""
    if not np.isfinite(x):
        return 0.0
    return float(f"%.{sig}g" % x)


def satellite() -> dict:
    """OPS-SAT-AD test segments in the 2D projection that actually separates.

    The axis pair is not chosen for looks. Every pair of the 19 columns was scored with a small
    random forest on the benchmark's own train/test split; `n_peaks` x `diff2_peaks` won at
    AUC-PR 0.8492 against a 0.2136 base rate. Runners-up were n_peaks x diff_peaks (0.8208) and
    len x diff2_peaks (0.8014). Recorded here so the choice is checkable rather than asserted.
    """
    src = REPO / "data-full" / "raw" / "opssat" / "dataset.csv"
    if not src.exists():
        print(f"  satellite: SKIP, {src} not present")
        return {}
    df = pd.read_csv(src)
    te = df[df.train == 0]
    pts = [[_round(r.n_peaks), _round(r.diff2_peaks), int(r.anomaly)] for r in te.itertuples()]
    return {
        "usecase": "satellite_comms",
        "is_training_corpus": True,
        "provenance": "OPS-SAT-AD, the corpus this page's published model is trained on - held-out "
                      "test split only, the benchmark's own split.",
        "licence": "CC-BY-4.0",
        "attribution": "Ruszczak et al., 'Machine learning detects terminal singularities', "
                       "OPS-SAT-AD benchmark, Scientific Data 2025, DOI 10.1038/s41597-025-05035-3. "
                       "ESA OPS-SAT mission data.",
        "x": {"key": "n_peaks", "label": "peaks in segment"},
        "y": {"key": "diff2_peaks", "label": "peaks in 2nd difference"},
        "class_names": ["nominal", "anomalous"],
        "separability_auc_pr": 0.8492,
        "base_rate": _round(float(te.anomaly.mean())),
        "note": "Chosen by scoring all 171 feature pairs on the benchmark split, not by eye. "
                "AUC-PR 0.8492 against a base rate of 0.2136 - the classes genuinely separate in "
                "this projection, which is what makes the model's decisions worth drawing on it.",
        "points": pts,
    }


def medical() -> dict:
    """WDBC - a DIFFERENT cohort and modality from the model's BreastMNIST, and it says so.

    This is deliberately not presented as the training data. BreastMNIST is 28x28 ultrasound;
    WDBC is 30 morphometric measurements of cell nuclei from fine-needle aspirates. They share a
    disease and nothing else. It is here because it is the only breast-cancer corpus in this repo
    with a licence that survives redistribution, and because showing a real, separable clinical
    corpus is still more informative than showing none.
    """
    try:
        from sklearn.datasets import load_breast_cancer
    except Exception as exc:                                  # pragma: no cover
        print(f"  medical: SKIP ({exc})")
        return {}
    d = load_breast_cancer()
    xi, yi = list(d.feature_names).index("mean radius"), list(d.feature_names).index("mean texture")
    # sklearn encodes 0=malignant, 1=benign. Emit 1=malignant so the positive class is the disease,
    # matching how every other use case in this repo orders its classes.
    pts = [[_round(r[xi]), _round(r[yi]), int(t == 0)] for r, t in zip(d.data, d.target)]
    return {
        "usecase": "medical_fl",
        "is_training_corpus": False,
        "provenance": "Wisconsin Diagnostic Breast Cancer (WDBC). NOT the model's training corpus - "
                      "the model trains on BreastMNIST ultrasound, and BreastMNIST cannot be "
                      "redistributed here because its CC BY attaches to the source ARTICLE rather "
                      "than to the data. This is a different cohort AND a different modality: "
                      "cell-nucleus morphometry from fine-needle aspirates.",
        "licence": "CC-BY-4.0",
        "attribution": "Wolberg, Mangasarian, Street & Street, UCI Machine Learning Repository, "
                       "DOI 10.24432/C5DW2B. Ships in scikit-learn.",
        "x": {"key": "mean radius", "label": "mean nucleus radius"},
        "y": {"key": "mean texture", "label": "mean nucleus texture"},
        "class_names": ["benign", "malignant"],
        "base_rate": _round(float(sum(1 for t in d.target if t == 0) / len(d.target))),
        "note": "Shown beside the model's scores, never on the same axes. Different modality means "
                "no shared feature space exists, so overlaying them would assert a correspondence "
                "that does not exist.",
        "points": pts,
    }


def main() -> int:
    for fn in (satellite, medical):
        payload = fn()
        if not payload:
            continue
        out = WEB / {"satellite_comms": "satellite", "medical_fl": "medical"}[payload["usecase"]]
        out.mkdir(parents=True, exist_ok=True)
        path = out / "real_2d.json"
        path.write_text(json.dumps(payload, separators=(",", ":")) + "\n")
        kb = path.stat().st_size / 1024
        print(f"  {payload['usecase']:16s} -> {path.relative_to(REPO)}  "
              f"{len(payload['points'])} points, {kb:.1f} KB, {payload['licence']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
