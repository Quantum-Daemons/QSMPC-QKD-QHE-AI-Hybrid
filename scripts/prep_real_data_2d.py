#!/usr/bin/env python3
"""Bundle a small, redistributable 2D slice of REAL data per use case, for the plot that sits
next to the private-inference result.

The point of this file is that a score plotted alone says how well the model separated the classes
and nothing about whether the classes are separable. A reader cannot tell a good model on easy data
from a mediocre model on hard data. Drawing the real corpus underneath the model's own decisions
answers that, and it is the only way to show a visitor what the encrypted path is actually up
against.

LICENCE IS THE BINDING CONSTRAINT, not size. Every slice here has to be redistributable inside a
public web bundle, which is a stricter test than "publicly downloadable" and knocks out most of the
obvious candidates. What each use case can and cannot do, checked 2026-08-10:

  satellite  OPS-SAT-AD, CC-BY-4.0. Redistributable, AND it is the corpus the published OPS-SAT
             models train on; the overlay is its test partition, which they were not fitted on. The
             page's anomaly demo used to score SMAP/MSL, for which no source grants a data licence
             (the Telemanom LICENSE is a Caltech copyright covering its software, and JPL is
             operated by Caltech, so 17 U.S.C. 105 does not reach it); since Round 84 it scores
             OPS-SAT-AD segments too (`scripts/data/build_heldout_payloads.py`).
  medical    (checked 2026-08-10; superseded 2026-10-26) BreastMNIST/BUSI was judged unusable here
             because the BUSI CC BY attaches to the article, not the data. Since 2026-10-26 this
             project redistributes BreastMNIST on MedMNIST's CC BY 4.0, by recorded decision (the
             BUSI authors state no licence; see the registry and DATA_LICENSES.md). This slice still
             uses WDBC (CC-BY-4.0, already bundled), labelled as a DIFFERENT COHORT AND MODALITY,
             because it is: cell-nucleus morphometry, not ultrasound. Overlaying it on the same axes
             would be a lie.
  genomics   1000 Genomes carries no blanket grant (IGSR says so itself), so the training corpus
             cannot ship. gnomAD v4.1 allele frequencies are CC0 and stand in as a reference
             population - again a substitute, not the training data, and labelled as one.
  finance    AMLworld is CDLA-Sharing-1.0. Usable, but share-alike propagates to the bundled slice.
  telecom    the corpus is generated by this repository, so there is no third party to ask - and no
             licence is granted for it either (the registry's DS_QKD_ATTACK_SYNTH), which the
             payload says rather than implying one. Since Round 84 it draws only the 600 rows held
             out from the published telecom models, not the 3,200-row corpus a QCNN trains on.

THE LICENCE TRAVELS WHOLE (Round 84). A name is not what CC BY 4.0 (s.3(a)(1)) or CDLA-Sharing-1.0
(s.3.1(b), s.3.3) ask of shared data: they ask for a link to the licence and a note of the changes.
Every payload carries `licence_url` and `modifications`, and the overlay renders both.

`corpus_is_synthetic` is carried per payload because the caption used to hardcode the word
"real" for every use case, and TWO of the five are not: AMLworld is synthetic by IBM's own
statement (a multi-agent simulator) and the telecom corpus is generated here. The finance page
had been saying "8192 real points" about simulator output long before telecom made it obvious.

Regenerate:  .venv/bin/python scripts/prep_real_data_2d.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
WEB = REPO / "web" / "public" / "data"
# THIS checkout's `qsh`, first. The venv may hold an editable install of another checkout, and the
# registry credits and the generator must come from the tree whose payloads this script writes.
sys.path.insert(0, str(REPO / "src"))


def _round(x: float, sig: int = 4) -> float:
    """Trim float noise so the bundle stays small and diffs stay readable."""
    if not np.isfinite(x):
        return 0.0
    return float(f"%.{sig}g" % x)


def _base_rate(labels) -> float:
    """Positive-class fraction. One definition, so a payload's `base_rate` field and any figure
    quoted in its `note` cannot disagree - which is what happened on the finance payload, where the
    field said 0.020020 and the prose said 0.0173 and the chart rendered both."""
    return float(sum(labels) / max(1, len(labels)))


def _separability(points) -> float:
    """Joint two-feature AUC-PR over the SHIPPED points: a 5-fold cross-validated random forest,
    200 trees, seed 0 - the estimator tests/test_the_separability_figure_reproduces.py states.

    Computed rather than written in since Round 71. Finance's literal stopped describing its points
    when they were redrawn from the held-out test window (0.2302 stated, 0.1269 on the new rows), and
    satellite's had never been this estimator's (0.8492 stated, 0.8057 measured); a tolerance of 0.08
    had admitted both, and on the new finance rows it would also have admitted the single-feature
    reading the band exists to exclude.
    """
    from sklearn.ensemble import RandomForestClassifier
    from sklearn.metrics import average_precision_score
    from sklearn.model_selection import cross_val_predict

    pts = np.asarray(points, dtype=float)
    x, y = pts[:, :2], pts[:, 2].astype(int)
    rf = RandomForestClassifier(n_estimators=200, random_state=0, n_jobs=-1)
    return _round(average_precision_score(
        y, cross_val_predict(rf, x, y, cv=5, method="predict_proba")[:, 1]))


#: How the computed figure is described wherever a payload quotes it.
SEPARABILITY_ESTIMATOR = "5-fold cross-validated two-feature random forest over these points"

#: Licence texts, linked from every payload under them (RD23).
CC_BY_4 = "https://creativecommons.org/licenses/by/4.0/"
CC0_1 = "https://creativecommons.org/publicdomain/zero/1.0/"
CDLA_SHARING_1 = "https://cdla.dev/sharing-1-0/"


def _registry():
    """The registry, for the credits: one copy of each attribution, not one per payload."""
    from qsh.models import registry

    return registry


def satellite() -> dict:
    """OPS-SAT-AD test segments in the 2D projection that actually separates.

    The axis pair is not chosen for looks. Every pair of the 19 columns was scored with a small
    random forest on the benchmark's own train/test split; `n_peaks` x `diff2_peaks` won at
    AUC-PR 0.8492 against a 0.2136 base rate. Runners-up were n_peaks x diff_peaks (0.8208) and
    len x diff2_peaks (0.8014). Recorded here so the choice is checkable rather than asserted.

    Those are the SELECTION figures, fitted on the train split and scored on test. The payload's
    `separability_auc_pr` is a different estimator, the one every payload uses (`_separability`), and
    until Round 71 it carried the selection figure under that estimator's name.

    THE SOURCE IS THE TRACKED EVALUATION SAMPLE (Round 84). The benchmark CSV under `data-full/` is not
    tracked, so this builder skipped satellite on any clone without it. `models/satellite_opssat/
    eval_sample.json` is the same test partition, entire, in the same order, and it is tracked.
    """
    src = REPO / "models" / "satellite_opssat" / "eval_sample.json"
    if not src.exists():
        print(f"  satellite: SKIP, {src} not present")
        return {}
    d = json.loads(src.read_text())
    names = d["feature_names"]
    xi, yi = names.index("n_peaks"), names.index("diff2_peaks")
    pts = [[_round(r[xi]), _round(r[yi]), int(t)] for r, t in zip(d["samples"], d["labels"], strict=True)]
    sep, base = _separability(pts), _round(_base_rate(d["labels"]))
    reg = _registry()
    return {
        "usecase": "satellite_comms",
        "corpus_is_synthetic": False,
        "is_training_corpus": True,
        "models": ["satellite_comms.opssat", "satellite_comms.opssat_student"],
        "provenance": "OPS-SAT-AD, real telemetry from ESA's OPS-SAT CubeSat: the benchmark's own "
                      "test partition, entire.",
        "split_note": f"None of these {len(pts)} segments was used to fit satellite_comms.opssat or "
                      "satellite_comms.opssat_student, which are fitted on the benchmark's train "
                      "partition. (The page's plaintext anomaly demo is a different regression, "
                      "fitted on 370 of these segments; its payload says so.)",
        "licence": "CC-BY-4.0",
        "licence_url": CC_BY_4,
        "attribution": f"{reg.DS_OPSSAT_AD.attribution} Data: Ruszczak, B., Kotowski, K., Nalepa, J. "
                       "& Evans, D., 'OPSSAT-AD - anomaly detection dataset for satellite telemetry', "
                       "Zenodo (2024), doi:10.5281/zenodo.12588358. ESA OPS-SAT mission data.",
        "modifications": f"Two of the 19 published per-segment features (n_peaks, diff2_peaks) of the "
                         f"{len(pts)} test-partition segments, rounded to 4 significant figures.",
        "x": {"key": "n_peaks", "label": "peaks in segment"},
        "y": {"key": "diff2_peaks", "label": "peaks in 2nd difference"},
        "class_names": ["nominal", "anomalous"],
        "separability_auc_pr": sep,
        "separability_method": SEPARABILITY_ESTIMATOR,
        "base_rate": base,
        "note": "Chosen by scoring all 171 feature pairs on the benchmark split, not by eye. "
                f"AUC-PR {sep} ({SEPARABILITY_ESTIMATOR}) against a base rate of {base}: the "
                "classes separate in this projection, which is why it is the plane a model's "
                "decisions are worth reading on. This figure draws the true labels only.",
        "points": pts,
    }


def medical() -> dict:
    """WDBC - a DIFFERENT cohort and modality from the published BreastMNIST models, and it says so.

    This is deliberately not presented as the training data of the published models. BreastMNIST
    is 28x28 ultrasound; WDBC is 30 morphometric measurements of cell nuclei from fine-needle
    aspirates. They share a disease and nothing else.

    BUT IT IS THE PAGE'S OWN ENCRYPTED MODEL'S CORPUS (Round 84). The regression the private-inference
    card encrypts is a WDBC regression whose eight inputs include both axes here, so "no shared
    feature space exists" was true of the BreastMNIST models and false of the model encrypted beside
    them. Its split is stated: rows 0-397 fitted it, rows 398-568 are held out and are the ones the
    card scores, on these same axes.
    """
    try:
        from sklearn.datasets import load_breast_cancer
    except Exception as exc:                                  # pragma: no cover
        print(f"  medical: SKIP ({exc})")
        return {}
    d = load_breast_cancer()
    xi, yi = list(d.feature_names).index("mean radius"), list(d.feature_names).index("mean texture")
    # sklearn encodes 0=malignant, 1=benign. Emit 1=malignant so the positive class is the disease,
    # matching how every other use case in this repo orders its classes - and, since Round 84, the
    # bundled breast_cancer_sample.json too.
    pts = [[_round(r[xi]), _round(r[yi]), int(t == 0)] for r, t in zip(d.data, d.target, strict=True)]
    cut = int(len(pts) * 0.7)          # the loader's scaler prefix, which the bundled regression fits
    reg = _registry()
    return {
        "usecase": "medical_fl",
        "corpus_is_synthetic": False,
        "is_training_corpus": False,
        "models": [],
        "provenance": "Wisconsin Diagnostic Breast Cancer (WDBC), cell-nucleus morphometry from "
                      "fine-needle aspirates. The published medical models train on BreastMNIST "
                      "ultrasound instead, whose 156-image test split this project publishes with "
                      "their evaluation samples on MedMNIST's CC BY 4.0 (the BUSI authors state no "
                      "licence of their own): a different cohort AND a different modality, so their "
                      "decisions are never drawn on these axes.",
        "split_note": f"All {len(pts)} rows. They ARE the corpus of the page's bundled WDBC "
                      f"regression, the model its private-inference card encrypts: rows 0 to "
                      f"{cut - 1} fitted it and rows {cut} to {len(pts) - 1} were held out, and the "
                      "card draws its encrypted decisions on those held-out rows on these axes.",
        "licence": "CC-BY-4.0",
        "licence_url": CC_BY_4,
        "attribution": f"{reg.DS_WDBC.attribution} Ships in scikit-learn.",
        "modifications": "Two of the 30 features (mean radius, mean texture), rounded to 4 "
                         "significant figures; class recoded to 1 = malignant (the source codes "
                         "0 = malignant).",
        "x": {"key": "mean radius", "label": "mean nucleus radius"},
        "y": {"key": "mean texture", "label": "mean nucleus texture"},
        "class_names": ["benign", "malignant"],
        "base_rate": _round(float(sum(1 for t in d.target if t == 0) / len(d.target))),
        "note": "The BreastMNIST models share no feature space with these measurements, so nothing "
                "of theirs is drawn here. The bundled WDBC regression does share it - both axes "
                "are among its eight inputs - which is why its held-out decisions can be read on "
                "this plane.",
        "points": pts,
    }


