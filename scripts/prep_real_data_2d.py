def satellite() -> dict:
    """OPS-SAT-AD test segments in the 2D projection that actually separates.

    The axis pair is not chosen for looks. Every pair of the 19 columns was scored with a small
    random forest on the benchmark's own train/test split; `n_peaks` x `diff2_peaks` won at
    AUC-PR 0.8492 against a 0.2136 base rate. Runners-up were n_peaks x diff_peaks (0.8208) and
    len x diff2_peaks (0.8014). Recorded here so the choice is checkable rather than asserted.

    Those are the SELECTION figures, fitted on the train split and scored on test. The payload's
    `separability_auc_pr` is a different estimator, the one every payload uses (`_separability`), and
    until Round 71 it carried the selection figure under that estimator's name.

    THE SOURCE IS THE TRACKED EVALUATION SAMPLE (Round 84). The benchmark CSV under `data-full/` is not
    tracked, so this builder skipped satellite on any clone without it. `models/satellite_opssat/
    eval_sample.json` is the same test partition, entire, in the same order, and it is tracked.
    """
    src = REPO / "models" / "satellite_opssat" / "eval_sample.json"
    if not src.exists():
        print(f"  satellite: SKIP, {src} not present")
        return {}
    d = json.loads(src.read_text())
    names = d["feature_names"]
    xi, yi = names.index("n_peaks"), names.index("diff2_peaks")
    pts = [[_round(r[xi]), _round(r[yi]), int(t)] for r, t in zip(d["samples"], d["labels"], strict=True)]
    sep, base = _separability(pts), _round(_base_rate(d["labels"]))
    reg = _registry()
    return {
        "usecase": "satellite_comms",
        "corpus_is_synthetic": False,
        "is_training_corpus": True,
        "models": ["satellite_comms.opssat", "satellite_comms.opssat_student"],
        "provenance": "OPS-SAT-AD, real telemetry from ESA's OPS-SAT CubeSat: the benchmark's own "
                      "test partition, entire.",
        "split_note": f"None of these {len(pts)} segments was used to fit satellite_comms.opssat or "
                      "satellite_comms.opssat_student, which are fitted on the benchmark's train "
                      "partition. (The page's plaintext anomaly demo is a different regression, "
                      "fitted on 370 of these segments; its payload says so.)",
        "licence": "CC-BY-4.0",
        "licence_url": CC_BY_4,
        "attribution": f"{reg.DS_OPSSAT_AD.attribution} ESA OPS-SAT mission data.",
        "modifications": f"Two of the 19 published per-segment features (n_peaks, diff2_peaks) of the "
                         f"{len(pts)} test-partition segments, rounded to 4 significant figures.",
        "x": {"key": "n_peaks", "label": "peaks in segment"},
        "y": {"key": "diff2_peaks", "label": "peaks in 2nd difference"},
        "class_names": ["nominal", "anomalous"],
        "separability_auc_pr": sep,
        "separability_method": SEPARABILITY_ESTIMATOR,
        "base_rate": base,
        "note": "Chosen by scoring all 171 feature pairs on the benchmark split, not by eye. "
                f"AUC-PR {sep} ({SEPARABILITY_ESTIMATOR}) against a base rate of {base}: the "
                "classes separate in this projection, which is why it is the plane a model's "
                "decisions are worth reading on. This figure draws the true labels only.",
        "points": pts,
    }


def medical() -> dict:
    """WDBC - a DIFFERENT cohort and modality from the published BreastMNIST models, and it says so.

    This is deliberately not presented as the training data of the published models. BreastMNIST
    is 28x28 ultrasound; WDBC is 30 morphometric measurements of cell nuclei from fine-needle
    aspirates. They share a disease and nothing else.

    BUT IT IS THE PAGE'S OWN ENCRYPTED MODEL'S CORPUS (Round 84). The regression the private-inference
    card encrypts is a WDBC regression whose eight inputs include both axes here, so "no shared
    feature space exists" was true of the BreastMNIST models and false of the model encrypted beside
    them. Its split is stated: rows 0-397 fitted it, rows 398-568 are held out and are the ones the
    card scores, on these same axes.
    """
    try:
        from sklearn.datasets import load_breast_cancer
    except Exception as exc:                                  # pragma: no cover
        print(f"  medical: SKIP ({exc})")
        return {}
    d = load_breast_cancer()
    xi, yi = list(d.feature_names).index("mean radius"), list(d.feature_names).index("mean texture")
    # sklearn encodes 0=malignant, 1=benign. Emit 1=malignant so the positive class is the disease,
    # matching how every other use case in this repo orders its classes - and, since Round 84, the
    # bundled breast_cancer_sample.json too.
    pts = [[_round(r[xi]), _round(r[yi]), int(t == 0)] for r, t in zip(d.data, d.target, strict=True)]
    cut = int(len(pts) * 0.7)          # the loader's scaler prefix, which the bundled regression fits
    reg = _registry()
    return {
        "usecase": "medical_fl",
        "corpus_is_synthetic": False,
        "is_training_corpus": False,
        "models": [],
        "provenance": "Wisconsin Diagnostic Breast Cancer (WDBC), cell-nucleus morphometry from "
                      "fine-needle aspirates. The published medical models train on BreastMNIST "
                      "ultrasound instead, whose 156-image test split this project publishes with "
                      "their evaluation samples on MedMNIST's CC BY 4.0 (the BUSI authors state no "
                      "licence of their own): a different cohort AND a different modality, so their "
                      "decisions are never drawn on these axes.",
        "split_note": f"All {len(pts)} rows. They ARE the corpus of the page's bundled WDBC "
                      f"regression, the model its private-inference card encrypts: rows 0 to "
                      f"{cut - 1} fitted it and rows {cut} to {len(pts) - 1} were held out, and the "
                      "card draws its encrypted decisions on those held-out rows on these axes.",
        "licence": "CC-BY-4.0",
        "licence_url": CC_BY_4,
        "attribution": f"{reg.DS_WDBC.attribution} Ships in scikit-learn.",
        "modifications": "Two of the 30 features (mean radius, mean texture), rounded to 4 "
                         "significant figures; class recoded to 1 = malignant (the source codes "
                         "0 = malignant).",
        "x": {"key": "mean radius", "label": "mean nucleus radius"},
        "y": {"key": "mean texture", "label": "mean nucleus texture"},
        "class_names": ["benign", "malignant"],
        "base_rate": _round(float(sum(1 for t in d.target if t == 0) / len(d.target))),
        "note": "The BreastMNIST models share no feature space with these measurements, so nothing "
                "of theirs is drawn here. The bundled WDBC regression does share it - both axes "
                "are among its eight inputs - which is why its held-out decisions can be read on "
                "this plane.",
        "points": pts,
    }


def _finance_window_counts() -> tuple[int, int]:
    """(laundering rows, all rows) of the finance held-out test window, as the trainer counted them.

    From `models/metrics.json` (`finance_aml.gbm`, `calibration.corp_raw`), cross-checked against the
    record's own `n_test` and `auprc_baseline` so a stale copy of either is refused, not quoted.
    """
    rec = json.loads((REPO / "models" / "metrics.json").read_text())["finance_aml.gbm"]
    corp = rec["calibration"]["corp_raw"]
    pos, n = int(corp["positives"]), int(corp["n"])
    assert n == int(rec["n_test"]), f"calibration n {n} against n_test {rec['n_test']}"
    assert abs(pos / n - float(rec["auprc_baseline"])) < 1e-12, "positives disagree with auprc_baseline"
    return pos, n


def _separability_at_rate(points, w_pos: float, w_neg: float) -> float:
    """`_separability`'s out-of-fold scores, with average precision weighted to another prevalence.

    The forest, folds and seed are `_separability`'s, so the scores are the same ones; only the
    precision changes, by counting each positive row `w_pos` times and each negative row `w_neg`
    times. For a class-stratified random draw that is the inverse of each class's sampling fraction,
    which turns the sample's precision-recall curve into an estimate of the source population's.
    """
    from sklearn.ensemble import RandomForestClassifier
    from sklearn.metrics import average_precision_score
    from sklearn.model_selection import cross_val_predict

    pts = np.asarray(points, dtype=float)
    x, y = pts[:, :2], pts[:, 2].astype(int)
    rf = RandomForestClassifier(n_estimators=200, random_state=0, n_jobs=-1)
    scores = cross_val_predict(rf, x, y, cv=5, method="predict_proba")[:, 1]
    return float(average_precision_score(y, scores, sample_weight=np.where(y == 1, w_pos, w_neg)))


def _finance_tail() -> dict:
    """The latest finance test-window tail measurement (scripts/measure_finance_test_window_tail.py).

    Read from the measurement rather than restated, so the caption cannot drift from it (Round 86).
    """
    found = sorted((REPO / "docs" / "measurements").glob("finance-test-window-tail-*.json"))
    if not found:
        raise SystemExit("no finance-test-window-tail measurement: run scripts/measure_finance_test_window_tail.py")
    return json.loads(found[-1].read_text())


def finance_tail_sentence(t: dict) -> str:
    """One sentence on the rows after HI-Small's ten days, with the scores they move. Shared with the test."""
    fw, wt, tl = t["full_window"], t["without_tail"], t["tail_only"]
    return (f"That window runs to {t['test_window']['last'][:10]}, past HI-Small's ten days of data, "
            "September 1-10 (IBM's dataset card): "
            f"{tl['rows']:,} of its rows fall on September 11-18, which the dataset's creator says are there so "
            "that laundering patterns begun earlier can complete, and "
            f"{tl['positives']:,} of them, {t['tail_share_of_window_positives']:.1%} of the window's "
            f"{fw['positives']:,} laundering rows, are laundering. Without them the window's rate is "
            f"{100 * wt['base_rate']:.3f} percent rather than {100 * fw['base_rate']:.3f}, the teacher's "
            f"minority-class F1 {wt['teacher']['minority_class_f1']:.4f} rather than "
            f"{fw['teacher']['minority_class_f1']:.4f} and the student's "
            f"{wt['student']['minority_class_f1']:.4f} rather than {fw['student']['minority_class_f1']:.4f}; "
            "the published 60/20/20 split's test set carries the same tail.")


def finance() -> dict:
    """AMLworld in the feature space the model actually consumes, not the raw transaction fields.

    Plotting `Amount Paid` against `Timestamp` would show no separation at all and imply the task is
    impossible. It is not - the separation lives in the GRAPH features, which is the whole reason the
    teacher computes them. So this draws the model's own feature space, taken from the published
    evaluation sample so the points are literally the rows the browser scores.

    The pair was re-measured on the CLEAN sample. An earlier measurement, taken before the
    `nrows=400_000` label leak was found, put the best pair at 0.8330 with `hour_of_day` in all top
    six; that reading was an artefact and is void. On clean rows the best pair containing
    `hour_of_day` collapses to 0.1302.

    SEPARABILITY AND READABILITY ARE DIFFERENT CRITERIA, and ranking on the first alone produced an
    unreadable chart. The AUC-PR winner is `format_risk` x `src_bank_diversity` at 0.3195, but
    `format_risk` has only SIX distinct values, five of them bunched near zero and one at 0.0075, so
    8192 points rendered as a few bands hard against the origin plus a lone outlier. A tree does not
    care how values are spaced; an eye does. Measured alternatives:

        format_risk x src_bank_diversity     0.1400   unreadable (6 values, uneven)
        src_fan_out_ratio x src_burst_fanout 0.1269   readable with a log y-axis   <- chosen
        src_fan_out_ratio x dst_fan_in_ratio 0.1179   readable, barely separates

    Re-measured in Round 71 on the held-out rows the sample is now drawn from, with the causal
    per-account features the model was trained on; on the old whole-corpus rows the three read
    0.3195, 0.2302 and 0.0764 and the choice was the same. So this ships the middle one: the best of
    the readable pairs, 1,656 and 40 distinct values, and `src_burst_fanout` log-scaled because its
    95th percentile is 7,801 against a maximum of 12,538. Class medians differ visibly on both axes -
    fan-out ratio 0.3333 for laundering against 0.1111 for legitimate.

    About 0.13 is a low number and that is the honest picture: AML in two dimensions is hard, which
    is consistent with this project's documented gap against published GFP+XGBoost rather than in
    tension with it. A plot that made it look easy would be the misleading one.

    LICENCE NOTE: AMLworld is CDLA-Sharing-1.0, which is SHARE-ALIKE. This slice is a derived
    database and carries the same terms - unlike the CC-BY-4.0 satellite and medical slices, it is
    not simply attribution-and-go.

    THE ROWS ARE ENRICHED, AND THE PAYLOAD SAYS BY HOW MUCH. The sample holds laundering at 2.0
    percent while its test window holds it at 0.15 percent, and AUC-PR's baseline is the prevalence,
    so both the figure and the lift the caption prints are properties of the enriched rows. The
    payload states the two rates and also carries the same out-of-fold scores re-weighted to the
    window's rate (`_separability_at_rate`).
    """
    src = REPO / "models" / "finance_aml_gbm" / "eval_sample.json"
    if not src.exists():
        print("  finance: SKIP, no eval_sample.json")
        return {}
    d = json.loads(src.read_text())
    names = d["feature_names"]
    xi, yi = names.index("src_fan_out_ratio"), names.index("src_burst_fanout")
    rows = d["samples"]
    labels = d["labels"]
    pts = [[_round(r[xi]), _round(r[yi]), int(t)] for r, t in zip(rows, labels, strict=True)]
    sep, base = _separability(pts), _round(_base_rate(labels))
    # The unreadable winner, scored the same way on the same rows, so the note's comparison is
    # computed too.
    fi, bi = names.index("format_risk"), names.index("src_bank_diversity")
    rival = _separability([[_round(r[fi]), _round(r[bi]), int(t)]
                           for r, t in zip(rows, labels, strict=True)])
    # The window the rows were drawn from, at its own prevalence (the trainer's count), and the
    # inverse-probability weights a class-stratified random draw from it implies.
    win_pos, win_n = _finance_window_counts()
    s_pos, s_n = int(sum(labels)), len(labels)
    w_pos, w_neg = win_pos / s_pos, (win_n - win_pos) / (s_n - s_pos)
    win_rate = win_pos / win_n
    sep_win = _separability_at_rate(pts, w_pos, w_neg)
    factor = (s_pos / s_n) / win_rate
    return {
        "usecase": "finance_aml",
        "corpus_is_synthetic": True,
        "is_training_corpus": True,
        "models": ["finance_aml.gbm", "finance_aml.student"],
        "provenance": "IBM AMLworld HI-Small - the exact rows the browser scores, a draw from the "
                      "held-out temporal test window, in the 32-feature graph space the teacher "
                      "consumes. Raw transaction fields are "
                      "deliberately not used: amount against time shows no separation and would "
                      "imply the task is impossible, when the signal is in the graph structure.",
        "split_note": f"None of these {len(pts):,} rows was used to fit, tune or calibrate "
                      "finance_aml.gbm or finance_aml.student: they come from the last 30 percent "
                      "of the transactions in time order. Laundering is enriched about "
                      f"{factor:.0f}x, to {100 * s_pos / s_n:.1f} percent ({s_pos:,} of {s_n:,}), "
                      f"against {100 * win_rate:.2f} percent in that window ({win_pos:,} of "
                      f"{win_n:,}), so the AUC-PR, base rate and lift below are measured on the "
                      "enriched rows. The private-inference card encrypts the student on exactly "
                      "these rows. " + finance_tail_sentence(_finance_tail()),
        # The two prevalences behind that sentence, as numbers, with where the window's comes from.
        "enrichment": {
            "sample_positives": s_pos, "sample_rows": s_n, "sample_rate": _round(s_pos / s_n),
            "window_positives": win_pos, "window_rows": win_n, "window_rate": _round(win_rate),
            "factor": round(factor, 2),
            "source": ("models/metrics.json, finance_aml.gbm calibration.corp_raw: the trainer's "
                       "count over all rows of the held-out test window"),
        },
        "licence": "CDLA-Sharing-1.0",
        "licence_url": CDLA_SHARING_1,
        "attribution": "Altman, Blanusa, von Niederhausern, Egressy, Anghel & Atasu, 'Realistic "
                       "Synthetic Financial Transactions for Anti-Money Laundering Models', "
                       "NeurIPS 2023 Datasets & Benchmarks. Data: IBM Transactions for Anti-Money "
                       "Laundering (AML), IBM Research. Corpus is synthetic by IBM's own "
                       "statement, generated by a multi-agent simulator.",
        "modifications": f"Two of the 32 computed graph features (src_fan_out_ratio, "
                         f"src_burst_fanout) of {len(pts)} test-window rows drawn with laundering "
                         "enriched to 2 percent, rounded to 4 significant figures. Enhanced Data "
                         "shared under the same CDLA-Sharing-1.0 (share-alike).",
        "x": {"key": "src_fan_out_ratio", "label": "source fan-out ratio"},
        "y": {"key": "src_burst_fanout", "label": "source burst fan-out", "scale": "log"},
        "class_names": ["legitimate", "laundering"],
        # COMPUTED by `_separability`, the estimator the reproduction gate states; it was a literal
        # until Round 71 and went stale when the rows were redrawn from the test window.
        "separability_auc_pr": sep,
        "separability_method": SEPARABILITY_ESTIMATOR,
        "base_rate": base,
        # The same out-of-fold scores at the window's own prevalence. A second figure, not a
        # correction of the first: lift is not invariant to prevalence, so the two differ.
        "separability_auc_pr_at_window_rate": _round(sep_win),
        "separability_at_window_rate_method": (
            "the same out-of-fold scores, with each laundering row weighted "
            f"{win_pos:,}/{s_pos:,} and each legitimate row {win_n - win_pos:,}/{s_n - s_pos:,} "
            "(the inverse of each class's sampling fraction), so the precision is the window's"),
        "note": f"AUC-PR {sep} ({SEPARABILITY_ESTIMATOR}) against a {base} base rate is a lift "
                f"of {sep / max(base, 1e-12):.1f}x on these enriched rows, and still a LOW number. "
                f"Re-weighted to the window's own {_round(win_rate)} rate, the same scores give "
                f"AUC-PR {_round(sep_win)}, a lift of {sep_win / win_rate:.1f}x; AUC-PR and its "
                "lift both move with prevalence, so the two pairs are different figures, not one "
                "corrected. "
                "That is the honest picture - two features do not solve AML, and a projection that "
                "looked easy would be the misleading one. NOT the highest-scoring pair available "
                f"(format_risk x src_bank_diversity reaches {rival}) because that one has six "
                "distinct values and renders as bands against the origin: separability and "
                "readability are different criteria and this chart needs both.",
        "points": pts,
    }


#: How far gnomAD's non-Finnish European frequency of a variant's effect allele may sit from the same
#: allele's frequency over 1000 Genomes' 503 European individuals before the point is left out. Both are
#: read from one Ensembl record and one resolved allele (scripts/fetch_gnomad_af.py), so a lookup cannot
#: land on another variant; this catches the remaining failure, an allele that one table spells or
#: counts differently from the other. Equal to the dosage resolver's AF_TOLERANCE
#: (scripts/data/fetch_g1k_dosages.py), which a test pins.
GNOMAD_AF_TOLERANCE = 0.1

#: The two gnomAD genome groups the overlay draws. East Asian against non-Finnish European because that
#: is the gap the ancestry-strata chart shows for PGS000072: one global cut flags 39.1% of 1000 Genomes'
#: EAS individuals against 1.7% to 4.0% of the other four groups (models/metrics.json).
GNOMAD_X, GNOMAD_Y = "eas", "nfe"
GNOMAD_GROUP_NAMES = {"eas": "East Asian (eas)", "nfe": "non-Finnish European (nfe)",
                      "afr": "African/African American (afr)"}


def _effect_allele_frequencies(path: Path) -> dict[str, float]:
    """rsID -> the scoring file's own `allelefrequency_effect`."""
    rows = [ln.split("\t") for ln in path.read_text().splitlines() if ln and not ln.startswith("#")]
    col = {name: j for j, name in enumerate(rows[0])}
    return {r[col["rsID"]]: float(r[col["allelefrequency_effect"]]) for r in rows[1:]}


def genomics() -> dict:
    """gnomAD effect-allele frequency in two ancestry groups, for the variants the page scores.

    NOT the page's genotypes, and the panel says so: one point per variant of the published score,
    positioned by how common its effect allele is in gnomAD's East Asian against its non-Finnish
    European genomes. On-diagonal means ancestry-invariant; off-diagonal means the allele frequency
    itself depends on ancestry, and weights fitted where the frequencies differ are how a distribution
    shift arises without any single weight being wrong.

    WHERE THE FREQUENCIES COME FROM. Ensembl's REST variation endpoint (release 116 when the cache was
    built), which lists gnomAD genome frequencies as populations `gnomADg:<group>`; no gnomAD service
    is queried. The cache keys each variant by the scoring file's rsID and holds the frequency of the
    allele the page's dosages count, resolved on the same record. gnomAD's data are CC0; its terms
    ask users not to attempt to reidentify participants and to give a link back.

    The class split is effect size, not disease: variants at or above the median weight carry more of
    the score, so an off-diagonal point in that class moves the distribution more.
    """
    src = REPO / "web" / "public" / "data" / "genomics" / "pgs000072_breast_cancer.json"
    af_path = REPO / "data" / "genomics" / "gnomad_af_pgs000072.json"
    scoring = REPO / "data" / "genomics" / "pgs000072_breast_cancer.tsv"
    if not src.exists() or not af_path.exists() or not scoring.exists():
        print("  genomics: SKIP, run scripts/fetch_gnomad_af.py and "
              "scripts/data/build_prs_browser_payload.py first")
        return {}
    prs = json.loads(src.read_text())
    af = json.loads(af_path.read_text())
    release = af.get("_source", {}).get("ensembl_release")
    w = {k: abs(float(x)) for k, x in zip(prs["keys"], prs["weights"], strict=True)}
    med = float(np.median(list(w.values())))
    pts, diverged_big, diverged_small, missing, mismatched = [], 0, 0, 0, 0
    for key in prs["keys"]:
        rec = af.get(key)
        if not rec or rec.get(GNOMAD_X) is None or rec.get(GNOMAD_Y) is None:
            missing += 1
            continue
        x, y = rec[GNOMAD_X], rec[GNOMAD_Y]
        if abs(y - rec["g1k_eur"]) > GNOMAD_AF_TOLERANCE:
            mismatched += 1
            continue
        big = 1 if w[key] >= med else 0
        pts.append([_round(x), _round(y), big])
        if abs(x - y) >= 0.20:
            if big:
                diverged_big += 1
            else:
                diverged_small += 1
    if not pts:
        return {}
    n_big = sum(p[2] for p in pts)
    n_score = len(prs["keys"])
    gx, gy = GNOMAD_GROUP_NAMES[GNOMAD_X], GNOMAD_GROUP_NAMES[GNOMAD_Y]
    left_out = []
    if missing:
        left_out.append(f"{missing} for which Ensembl lists no gnomAD frequency of the effect allele in "
                        f"one of the two groups")
    if mismatched:
        left_out.append(f"{mismatched} whose gnomAD {GNOMAD_Y} frequency is more than "
                        f"{GNOMAD_AF_TOLERANCE} from the same allele's 1000 Genomes EUR frequency")
    return {
        "usecase": "genomics",
        "corpus_is_synthetic": False,
        "is_training_corpus": False,
        "provenance": (f"gnomAD genome allele frequencies of the effect allele, as Ensembl's REST "
                       f"variation endpoint lists them (release {release}; populations "
                       f"gnomADg:{GNOMAD_X} and gnomADg:{GNOMAD_Y}; Ensembl does not name the gnomAD "
                       f"release), for the variants of PGS000072 this page scores. The page's own "
                       f"genotypes are 30 1000 Genomes individuals; this draws population-scale "
                       f"frequencies of the same alleles from a CC0 source (gnomAD's terms also have "
                       f"every user agree not to attempt to reidentify participants). Each point is "
                       f"one variant of the score itself, so this is the same modality from a "
                       f"different cohort, not a different measurement."),
        "models": [],
        "split_note": "Not rows of any model: one point per variant of the published score, which "
                      "was not fitted here.",
        "licence": "CC0-1.0",
        "licence_url": CC0_1,
        "attribution": (f"Genome Aggregation Database (gnomAD) genomes, Broad Institute "
                        f"(https://gnomad.broadinstitute.org/), read through Ensembl release {release}'s "
                        f"REST variation endpoint. CC0 - no attribution is required; it is given because "
                        f"gnomAD asks for it and a link back. gnomAD's terms bind users not to attempt "
                        f"to re-identify participants."),
        "modifications": (f"Effect-allele frequencies of {len(pts)} of the score's {n_score} scored "
                          f"variants, in gnomAD's {gx} and {gy} groups, keyed by rsID and rounded to 4 "
                          f"significant figures"
                          + (f"; left out: {'; '.join(left_out)}" if left_out else "")
                          + "; each variant classed by its absolute effect weight, at or above the median "
                            "or below it."),
        # Axis titles as short as the old ones: the y title is rotated in a 230 px chart. The groups
        # are named in full in `modifications` and `note`, which the caption prints.
        "x": {"key": f"af_{GNOMAD_X}", "label": f"effect-allele frequency, gnomAD {GNOMAD_X}"},
        "y": {"key": f"af_{GNOMAD_Y}", "label": f"effect-allele frequency, gnomAD {GNOMAD_Y}"},
        "class_names": ["weight below the median", "weight at or above the median"],
        "base_rate": _round(n_big / len(pts)),
        "note": (f"{len(pts)} of the {n_score} variants this page scores, each placed by its effect "
                 f"allele's frequency in gnomAD's {gx} against its {gy} genomes. The diagonal is "
                 f"ancestry-invariant; distance from it is the portability problem in its raw form. "
                 # Round 86: this said the larger-effect variants "are the weights that move a score across
                 # ancestries", while the smaller-effect ones diverge MORE often (26 of 69 against 31 of 108),
                 # and "larger" was half the score in name only: the weights are rounded, so ties at the
                 # median put 108 of 177 at or above it. Both rates are printed now, and neither is ranked.
                 f"The variants are split by absolute effect weight at the median, |log OR| {med:.4f} (an odds "
                 f"ratio of {float(np.exp(med)):.2f}); the published weights are rounded, so ties put {n_big} of "
                 f"the {len(pts)} at or above it. {diverged_big} of those {n_big} differ by at least 0.20 in "
                 f"frequency between the two groups, and {diverged_small} of the other {len(pts) - n_big}; a "
                 f"variant's pull on a score across groups is its weight times that gap. 98.1% of the GWAS "
                 f"samples behind PGS000072's weights are of European ancestry (the PGS Catalog's ancestry "
                 f"distribution for the score). This is the mechanism behind the ancestry-strata chart above, "
                 f"not a second finding."),
        "points": pts,
    }


def telecom() -> dict:
    """The held-out quarter of the seed-42 draw the published telecom models were evaluated on.

    Telecom was the ONLY use case with no `real_2d.json` until 2026-08-13, and the reason was not
    licence: the corpus is generated by this repository. What it drew was the problem (Round 84): all
    3,200 rows of `generate(n_per_class=400, seed=0)`, the call a QCNN trains on, so 70 percent of the
    points were training rows under a caption that called them a held-out split. It now draws the
    600 rows of `generate(n_per_class=300, seed=42)` that the trainer's stratified 75/25 split
    (random_state 42) holds out - the rows `telecom_ids.qml` and `telecom_ids.student` were scored
    on and never fitted on, and the rows the private-inference card encrypts the student over.

    BINARY BY NECESSITY, AND SAID SO. `VerificationChart` reads a point as `[x, y, label]` with a
    0/1 label, so an 8-class corpus has to collapse to normal-versus-attack to be plottable at all;
    the `note` says the models are scored on 8 classes instead.

    THE BASE RATE IS AN ARTEFACT. `attacks.generate` emits equal counts of all eight classes, seven of
    which are attacks, so 87.5% of rows are positive, and an AUC-PR near 0.99 is a lift of about 1.13x.

    ONE ESTIMATOR. The separability figure used to be the best of eight fixed linear directions here
    and a cross-validated random forest everywhere else, under the same sentence; it is now
    `_separability` like the others.
    """
    from sklearn.model_selection import train_test_split

    from qsh.qml_ids import attacks

    X, y, class_names = attacks.generate(n_per_class=300, seed=42)
    _tr, te = train_test_split(np.arange(len(y)), test_size=0.25, random_state=42, stratify=y)
    feats = list(attacks.FEATURES)
    labels = (y[te] != class_names.index("normal")).astype(int)
    # `qber_std` x `multiphoton_rate` is both the top-scoring pair and a readable one, with many
    # distinct values on each axis, so no banding against the origin.
    xi, yi = feats.index("qber_std"), feats.index("multiphoton_rate")
    pts = [[_round(float(r[xi])), _round(float(r[yi])), int(t)]
           for r, t in zip(X[te], labels, strict=True)]
    auc_pr, base = _separability(pts), _base_rate(labels)
    reg = _registry()
    return {
        "usecase": "telecom_ids",
        "corpus_is_synthetic": True,
        "is_training_corpus": True,
        "models": ["telecom_ids.qml", "telecom_ids.student"],
        "provenance": "SYNTHETIC QKD-session telemetry generated by qsh.qml_ids.attacks. Class "
                      "structure follows Al-Kuwari et al. (arXiv:2509.14282); the 7 features and "
                      "their values are this project's own. No public real QKD-attack "
                      "capture was found, which is why this is generated rather than collected - and "
                      "why no number here is a performance claim about a real link.",
        "split_note": f"The {len(pts)} rows held out from generate(n_per_class=300, seed=42) by the "
                      "trainer's stratified 75/25 split, 75 per class: none was used to fit "
                      "telecom_ids.qml or to distil telecom_ids.student, and the private-inference "
                      "card encrypts the student on exactly these rows. The QCNNs on this page train "
                      "on a different draw (seed 0).",
        "licence": reg.DS_QKD_ATTACK_SYNTH.licence,
        "licence_url": APACHE_2,
        "attribution": "Class structure per Al-Kuwari et al., arXiv:2509.14282. The rows "
                       "themselves are produced by this repository's own generator.",
        "modifications": "Two of the 7 features, rounded to 4 significant figures; the 8 classes "
                         "collapsed to normal against attack.",
        "x": {"key": "qber_std", "label": "QBER standard deviation"},
        "y": {"key": "multiphoton_rate", "label": "multiphoton rate"},
        "class_names": ["normal", "attack (any of 7)"],
        "separability_auc_pr": auc_pr,
        "separability_method": SEPARABILITY_ESTIMATOR,
        "base_rate": _round(base),
        # Round 86: this read "is only a 1.13x lift", but a base rate p caps the lift at 1/p (1.143x at
        # 0.875), so 1.13x is near the ceiling, not small. The share of the way from chance to perfect,
        # (AUC-PR - p) / (1 - p), is the reading that does not depend on p.
        "note": f"AUC-PR {auc_pr} against a {_round(base)} base rate: that base rate caps the lift at "
                f"{1 / max(base, 1e-12):.3f}x, and {auc_pr} sits {(auc_pr - base) / max(1 - base, 1e-12):.1%} "
                "of the way from chance to perfect. Its base rate is shown because the corpus is "
                "BALANCED ACROSS 8 CLASSES, seven of which are attacks, so 87.5% of rows are positive "
                "before any model looks at them, and the attacks are separable by construction. Note "
                "also that this plane collapses 8 classes to normal-versus-attack because the chart "
                "takes a binary label; the forest and the CKKS student on this page are scored on 8 "
                "classes instead, and the two numbers are not comparable.",
        "points": pts,
    }


def telecom_nidd() -> dict:
    """The held-out 5G-NIDD flows `telecom_ids.nidd` was scored on (Round 86).

    The telecom page has two corpora and until now only drew one, so with the 5G-NIDD model selected
    it showed rows that model never saw. These are real flows under CC BY 4.0, from the same
    per-class-floored draw of the held-out quarter the published evaluation sample holds; 4,096 of its
    16,379 rows, by a seeded permutation, keep the payload the size of the others.

    `sMeanPktSz` and `TotBytes` are two of the 46 columns the model reads. The file label `IdleTime` is
    not one of them, and it would have been the obvious pair member: it separates the classes best of all.
    """
    path = REPO / "models" / "telecom_nidd" / "eval_sample.json"
    if not path.exists():
        return {}
    sample = json.loads(path.read_text())
    names = sample["feature_names"]
    xs = np.asarray(sample["samples"], dtype=float)
    ys = np.asarray(sample["labels"], dtype=int)
    benign = sample["class_names"].index("Benign")
    keep = np.random.default_rng(42).permutation(len(ys))[:4096]
    xi, yi = names.index("sMeanPktSz"), names.index("TotBytes")
    labels = (ys[keep] != benign).astype(int)
    pts = [[_round(float(xs[k, xi])), _round(float(xs[k, yi])), int(t)]
           for k, t in zip(keep, labels, strict=True)]
    auc_pr, base = _separability(pts), _base_rate(labels)
    reg = _registry()
    ds = reg.DS_5G_NIDD
    return {
        "dir": "telecom_nidd",
        "usecase": "telecom_ids",
        "corpus_is_synthetic": False,
        "is_training_corpus": True,
        "models": ["telecom_ids.nidd"],
        "provenance": "5G-NIDD: real traffic from a 5G test network at the University of Oulu, as flow "
                      "statistics. This is the network layer, a different task from the QKD-layer "
                      "attacks the other model on this page classifies, with no feature in common.",
        "split_note": f"{len(pts):,} rows from the published evaluation sample, a per-class-floored draw "
                      "of the held-out quarter of the seed-42 stratified split: none was used to fit "
                      "telecom_ids.nidd. The floor over-represents the rare attacks, so the base rate "
                      "here is the sample's and not the corpus's.",
        "licence": ds.licence,
        "licence_url": CC_BY_4,
        "attribution": ds.attribution,
        "modifications": "Two of the 113 columns, rounded to 4 significant figures, on 4,096 rows of a "
                         "stratified held-out draw, after removing the 281,529 Benign-labelled copies of "
                         "flows the file also labels UDPFlood; the 8 attack classes collapsed to attack "
                         "against benign.",
        "x": {"key": "sMeanPktSz", "label": "mean packet size from the source (bytes)"},
        "y": {"key": "TotBytes", "label": "total bytes in the flow", "scale": "log"},
        "class_names": ["Benign", "attack (any of 8)"],
        "separability_auc_pr": auc_pr,
        "separability_method": SEPARABILITY_ESTIMATOR,
        "base_rate": _round(base),
        "note": f"AUC-PR {auc_pr} against a {_round(base)} base rate. On these two columns benign flows "
                "sit at larger mean packet sizes than most attacks; telling the eight attacks apart takes "
                "the other columns. The model reads 46 and scores accuracy 0.9979 over 9 classes. The "
                "file holds one attacker's UDP flood twice under contradictory labels, and the Benign "
                "copy is removed before anything here is drawn.",
        "points": pts,
    }


def main() -> int:
    for fn in (satellite, medical, finance, genomics, telecom, telecom_nidd):
        payload = fn()
        if not payload:
            continue
        out = WEB / (payload.pop("dir", None) or {"satellite_comms": "satellite", "medical_fl": "medical",
                     "finance_aml": "finance", "genomics": "genomics",
                     "telecom_ids": "telecom"}[payload["usecase"]])
        out.mkdir(parents=True, exist_ok=True)
        path = out / "real_2d.json"
        path.write_text(json.dumps(payload, separators=(",", ":")) + "\n")
        kb = path.stat().st_size / 1024
        print(f"  {payload['usecase']:16s} -> {path.relative_to(REPO)}  "
              f"{len(payload['points'])} points, {kb:.1f} KB, {payload['licence']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
