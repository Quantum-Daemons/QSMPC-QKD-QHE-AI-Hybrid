#!/usr/bin/env python3
"""Bundle a small, redistributable 2D slice of REAL data per use case, for the plot that sits
next to the private-inference result.

The point of this file is that a score plotted alone says how well the model separated the classes
and nothing about whether the classes are separable. A reader cannot tell a good model on easy data
from a mediocre model on hard data. Drawing the real corpus underneath the model's own decisions
answers that, and it is the only way to show a visitor what the encrypted path is actually up
against.

LICENCE IS THE BINDING CONSTRAINT, not size. Every slice here has to be redistributable inside a
public web bundle, which is a stricter test than "publicly downloadable" and knocks out most of the
obvious candidates. What each use case can and cannot do, checked 2026-08-10:

  satellite  OPS-SAT-AD, CC-BY-4.0. Redistributable, AND it is the corpus the shipped model is
             actually trained on - so this is a genuine train-vs-inference comparison rather than a
             lookalike. Note the page currently bundles SMAP/MSL for its anomaly demo, which is NOT
             redistributable: 17 U.S.C. 105 removes US copyright domestically and is not a grant,
             and it is territorial. The redistributable corpus was not the one being shipped.
  medical    BreastMNIST/BUSI CANNOT be used - the CC BY there attaches to the article, not the
             data, and the host asks only to be cited. WDBC (CC-BY-4.0, already bundled) is used
             instead and is labelled as a DIFFERENT COHORT AND MODALITY, because it is: cell-nucleus
             morphometry, not ultrasound. Overlaying it on the same axes would be a lie.
  genomics   1000 Genomes carries no blanket grant (IGSR says so itself), so the training corpus
             cannot ship. gnomAD v4.1 allele frequencies are CC0 and stand in as a reference
             population - again a substitute, not the training data, and labelled as one.
  finance    AMLworld is CDLA-Sharing-1.0. Usable, but share-alike propagates to the bundled slice.
  telecom    the corpus is generated by this repository, so there is no third party to ask.

Regenerate:  .venv/bin/python scripts/prep_real_data_2d.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[1]
WEB = REPO / "web" / "public" / "data"


def _round(x: float, sig: int = 4) -> float:
    """Trim float noise so the bundle stays small and diffs stay readable."""
    if not np.isfinite(x):
        return 0.0
    return float(f"%.{sig}g" % x)


def satellite() -> dict:
    """OPS-SAT-AD test segments in the 2D projection that actually separates.

    The axis pair is not chosen for looks. Every pair of the 19 columns was scored with a small
    random forest on the benchmark's own train/test split; `n_peaks` x `diff2_peaks` won at
    AUC-PR 0.8492 against a 0.2136 base rate. Runners-up were n_peaks x diff_peaks (0.8208) and
    len x diff2_peaks (0.8014). Recorded here so the choice is checkable rather than asserted.
    """
    src = REPO / "data-full" / "raw" / "opssat" / "dataset.csv"
    if not src.exists():
        print(f"  satellite: SKIP, {src} not present")
        return {}
    df = pd.read_csv(src)
    te = df[df.train == 0]
    pts = [[_round(r.n_peaks), _round(r.diff2_peaks), int(r.anomaly)] for r in te.itertuples()]
    return {
        "usecase": "satellite_comms",
        "is_training_corpus": True,
        "provenance": "OPS-SAT-AD, the corpus this page's published model is trained on - held-out "
                      "test split only, the benchmark's own split.",
        "licence": "CC-BY-4.0",
        "attribution": "Ruszczak, Kotowski, Evans & Nalepa, \'The OPS-SAT benchmark for "
                       "detecting anomalies in satellite telemetry\', Scientific Data 12, 710 "
                       "(2025), DOI 10.1038/s41597-025-05035-3. "
                       "ESA OPS-SAT mission data.",
        "x": {"key": "n_peaks", "label": "peaks in segment"},
        "y": {"key": "diff2_peaks", "label": "peaks in 2nd difference"},
        "class_names": ["nominal", "anomalous"],
        "separability_auc_pr": 0.8492,
        "base_rate": _round(float(te.anomaly.mean())),
        "note": "Chosen by scoring all 171 feature pairs on the benchmark split, not by eye. "
                "AUC-PR 0.8492 against a base rate of 0.2136 - the classes genuinely separate in "
                "this projection, which is what makes the model's decisions worth drawing on it.",
        "points": pts,
    }


def medical() -> dict:
    """WDBC - a DIFFERENT cohort and modality from the model's BreastMNIST, and it says so.

    This is deliberately not presented as the training data. BreastMNIST is 28x28 ultrasound;
    WDBC is 30 morphometric measurements of cell nuclei from fine-needle aspirates. They share a
    disease and nothing else. It is here because it is the only breast-cancer corpus in this repo
    with a licence that survives redistribution, and because showing a real, separable clinical
    corpus is still more informative than showing none.
    """
    try:
        from sklearn.datasets import load_breast_cancer
    except Exception as exc:                                  # pragma: no cover
        print(f"  medical: SKIP ({exc})")
        return {}
    d = load_breast_cancer()
    xi, yi = list(d.feature_names).index("mean radius"), list(d.feature_names).index("mean texture")
    # sklearn encodes 0=malignant, 1=benign. Emit 1=malignant so the positive class is the disease,
    # matching how every other use case in this repo orders its classes.
    pts = [[_round(r[xi]), _round(r[yi]), int(t == 0)] for r, t in zip(d.data, d.target)]
    return {
        "usecase": "medical_fl",
        "is_training_corpus": False,
        "provenance": "Wisconsin Diagnostic Breast Cancer (WDBC). NOT the model's training corpus - "
                      "the model trains on BreastMNIST ultrasound, and BreastMNIST cannot be "
                      "redistributed here because its CC BY attaches to the source ARTICLE rather "
                      "than to the data. This is a different cohort AND a different modality: "
                      "cell-nucleus morphometry from fine-needle aspirates.",
        "licence": "CC-BY-4.0",
        "attribution": "Wolberg, Mangasarian, Street & Street, UCI Machine Learning Repository, "
                       "DOI 10.24432/C5DW2B. Ships in scikit-learn.",
        "x": {"key": "mean radius", "label": "mean nucleus radius"},
        "y": {"key": "mean texture", "label": "mean nucleus texture"},
        "class_names": ["benign", "malignant"],
        "base_rate": _round(float(sum(1 for t in d.target if t == 0) / len(d.target))),
        "note": "Shown beside the model's scores, never on the same axes. Different modality means "
                "no shared feature space exists, so overlaying them would assert a correspondence "
                "that does not exist.",
        "points": pts,
    }


def finance() -> dict:
    """AMLworld in the feature space the model actually consumes, not the raw transaction fields.

    Plotting `Amount Paid` against `Timestamp` would show no separation at all and imply the task is
    impossible. It is not - the separation lives in the GRAPH features, which is the whole reason the
    teacher computes them. So this draws the model's own feature space, taken from the published
    evaluation sample so the points are literally the rows the browser scores.

    The pair was re-measured on the CLEAN sample. An earlier measurement, taken before the
    `nrows=400_000` label leak was found, put the best pair at 0.8330 with `hour_of_day` in all top
    six; that reading was an artefact and is void. On clean rows the best pair containing
    `hour_of_day` collapses to 0.1302.

    SEPARABILITY AND READABILITY ARE DIFFERENT CRITERIA, and ranking on the first alone produced an
    unreadable chart. The AUC-PR winner is `format_risk` x `src_bank_diversity` at 0.3195, but
    `format_risk` has only SIX distinct values, five of them bunched near zero and one at 0.0075, so
    8192 points rendered as a few bands hard against the origin plus a lone outlier. A tree does not
    care how values are spaced; an eye does. Measured alternatives:

        format_risk x src_bank_diversity     0.3195   unreadable (6 values, uneven)
        src_fan_out_ratio x src_burst_fanout 0.2302   readable with a log y-axis   <- chosen
        src_fan_out_ratio x dst_fan_in_ratio 0.0764   readable, barely separates

    So this ships the middle one: 13.3x lift over the 0.0173 base rate, 848 and 37 distinct values,
    and `src_burst_fanout` log-scaled because its 95th percentile is 7,801 against a maximum of
    12,540. Class medians differ visibly on both axes - fan-out ratio 0.4865 for laundering against
    0.0943 for legitimate.

    0.23 is a low number and that is the honest picture: AML in two dimensions is hard, which is
    consistent with this project's documented gap against published GFP+XGBoost rather than in
    tension with it. A plot that made it look easy would be the misleading one.

    LICENCE NOTE: AMLworld is CDLA-Sharing-1.0, which is SHARE-ALIKE. This slice is a derived
    database and carries the same terms - unlike the CC-BY-4.0 satellite and medical slices, it is
    not simply attribution-and-go.
    """
    src = REPO / "models" / "finance_aml_gbm" / "eval_sample.json"
    if not src.exists():
        print("  finance: SKIP, no eval_sample.json")
        return {}
    d = json.loads(src.read_text())
    names = d["feature_names"]
    xi, yi = names.index("src_fan_out_ratio"), names.index("src_burst_fanout")
    rows = d["samples"]
    labels = d["labels"]
    pts = [[_round(r[xi]), _round(r[yi]), int(t)] for r, t in zip(rows, labels)]
    return {
        "usecase": "finance_aml",
        "is_training_corpus": True,
        "provenance": "IBM AMLworld HI-Small - the exact held-out rows the browser scores, in the "
                      "32-feature graph space the teacher consumes. Raw transaction fields are "
                      "deliberately not used: amount against time shows no separation and would "
                      "imply the task is impossible, when the signal is in the graph structure.",
        "licence": "CDLA-Sharing-1.0 (SHARE-ALIKE - this derived slice carries the same terms)",
        "attribution": "Altman, Blanusa, von Niederhausern, Egressy, Anghel & Atasu, 'Realistic "
                       "Synthetic Financial Transactions for Anti-Money Laundering Models', "
                       "NeurIPS 2023 Datasets & Benchmarks. Corpus is synthetic by IBM's own "
                       "statement, generated by a multi-agent simulator.",
        "x": {"key": "src_fan_out_ratio", "label": "source fan-out ratio"},
        "y": {"key": "src_burst_fanout", "label": "source burst fan-out", "scale": "log"},
        "class_names": ["legitimate", "laundering"],
        "separability_auc_pr": 0.2302,
        "base_rate": _round(float(sum(labels) / max(1, len(labels)))),
        "note": "AUC-PR 0.2302 against a 0.0173 base rate is a 13.3x lift and still a LOW number. "
                "That is the honest picture - two features do not solve AML, and a projection that "
                "looked easy would be the misleading one. NOT the highest-scoring pair available "
                "(format_risk x src_bank_diversity reaches 0.3195) because that one has six "
                "distinct values and renders as bands against the origin: separability and "
                "readability are different criteria and this chart needs both.",
        "points": pts,
    }


def genomics() -> dict:
    """gnomAD allele frequency, AFR against European, for the 77 variants the score is built from.

    NOT the training corpus, and the panel says so. The page scores real 1000 Genomes genotypes, but
    IGSR grants no blanket redistribution licence - it states that itself - so the training data
    cannot ship. gnomAD v4 is CC0, the strongest available position: no attribution obligation, no
    share-alike, no field-of-use limit.

    WHY THIS PROJECTION. The page already shows one globally-set high-risk cut flagging 29.35% of AFR
    against 3.75% of AMR. That chart STATES the disparity. This one EXPLAINS it: each point is one of
    the score's own variants, positioned by how common it is in African-ancestry against
    European-ancestry samples. On-diagonal means ancestry-invariant; off-diagonal means the allele
    frequency itself depends on ancestry. PGS000001 was fitted on a 100% European cohort (22,627
    individuals, Mavaddat et al., JNCI 2015), so weights learned where frequencies differ are exactly
    how a distribution shift arises without any single weight being wrong.

    The class split is effect size, not disease: variants at or above the median |weight| carry more
    of the score, so an off-diagonal point in that class moves the distribution more than an
    off-diagonal point in the other.
    """
    src = REPO / "web" / "public" / "data" / "genomics" / "pgs000001_prs.json"
    af_path = REPO / "data" / "genomics" / "gnomad_af.json"
    if not src.exists() or not af_path.exists():
        print("  genomics: SKIP, run scripts/fetch_gnomad_af.py first")
        return {}
    prs = json.loads(src.read_text())
    af = json.loads(af_path.read_text())
    w = {rs: abs(float(x)) for rs, x in zip(prs["rsids"], prs["weights"])}
    med = float(np.median([v for v in w.values()]))
    pts, diverged_big = [], 0
    for rs, rec in af.items():
        if not rec or rec.get("afr") is None or rec.get("nfe") is None:
            continue
        big = 1 if w.get(rs, 0.0) >= med else 0
        pts.append([_round(rec["afr"]), _round(rec["nfe"]), big])
        if big and abs(rec["afr"] - rec["nfe"]) >= 0.20:
            diverged_big += 1
    if not pts:
        return {}
    n_big = sum(p[2] for p in pts)
    return {
        "usecase": "genomics",
        "is_training_corpus": False,
        "provenance": "gnomAD v4 allele frequencies for the 77 variants of PGS000001 - the page "
                      "scores 1000 Genomes genotypes, which carry no blanket redistribution "
                      "licence, so a CC0 reference population stands in. Each point is one variant "
                      "of the score itself, so this is the same modality from a different cohort, "
                      "not a different measurement.",
        "licence": "CC0-1.0",
        "attribution": "Genome Aggregation Database (gnomAD) v4, Broad Institute. CC0 - no "
                       "attribution is required; it is given because the data is worth crediting.",
        "x": {"key": "af_afr", "label": "allele frequency, African ancestry"},
        "y": {"key": "af_nfe", "label": "allele frequency, European ancestry"},
        "class_names": ["smaller effect weight", "larger effect weight"],
        "base_rate": _round(n_big / len(pts)),
        "note": (f"{len(pts)} of 77 variants resolved in gnomAD v4. The diagonal is "
                 f"ancestry-invariant; distance from it is the portability problem in its raw form. "
                 f"{diverged_big} of the {n_big} larger-effect variants differ by at least 0.20 in "
                 f"allele frequency between the two groups - and PGS000001's development cohort was "
                 f"100% European, so those are the weights doing the damage. This is the mechanism "
                 f"behind the ancestry-strata chart above, not a second finding."),
        "points": pts,
    }


def main() -> int:
    for fn in (satellite, medical, finance, genomics):
        payload = fn()
        if not payload:
            continue
        out = WEB / {"satellite_comms": "satellite", "medical_fl": "medical",
                     "finance_aml": "finance", "genomics": "genomics"}[payload["usecase"]]
        out.mkdir(parents=True, exist_ok=True)
        path = out / "real_2d.json"
        path.write_text(json.dumps(payload, separators=(",", ":")) + "\n")
        kb = path.stat().st_size / 1024
        print(f"  {payload['usecase']:16s} -> {path.relative_to(REPO)}  "
              f"{len(payload['points'])} points, {kb:.1f} KB, {payload['licence']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
