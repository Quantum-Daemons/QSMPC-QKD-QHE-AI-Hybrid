"""A licence printed without its qualifier is a stronger claim than the licence.

WHY THIS EXISTS

`report/build_data.py` rendered the Data licence column as
``esc(s.dataset.licence.split(";")[0][:22])``. Two truncations in one expression, and both cut from
the same end - the end where hedges live. Measured against the licences that actually reach the
table, **4 of 7 are altered and 3 of the 4 lose a qualifier**:

    CC-BY-4.0 asserted by MedMNIST; the upstream BUSI grant is NOT verifiable
        -> "CC-BY-4.0 asserted by "      both cuts fire: the `;` takes the caveat, [:22] the attributor
    per-score; EMBL-EBI Terms of Use by default
        -> "per-score"                   reads as a licence name; it is the opposite, a per-score condition
    provider's own pages state conflicting terms
        -> "provider's own pages s"
    generated by this repository
        -> "generated by this repo"      the only harmless one - nothing is hedged away

**Truncation is biased toward overclaiming, because a caveat comes last.** "CC-BY-4.0 asserted by "
tells a reader the corpus is CC-BY-4.0. The source sentence exists to say that the upstream grant
behind that assertion is NOT verifiable. This was published in `report/technical-report.pdf`.

WHY THE ASSERTION IS "PROPER PREFIX" AND NOT A LENGTH CHECK

A length check would catch `[:22]` and sail past `split(";")`, which is the half that removes the
most meaning. Both truncations produce a string that is a *proper prefix* of the source, so one
predicate covers both - and it keeps covering them if someone later re-introduces truncation at a
different width or on a different separator.

It also cannot be satisfied by the fix restating itself: this compares two artifacts, the tracked
generated `.tex` against `src/qsh/models/registry.py`, and the fix touches only one of them.

SCOPE, STATED

Only licences reachable from a `ModelSpec`. `registry.py` defines 11 `Dataset` objects and 4 of them
(`DS_1000G`, `DS_PAYSIM`, `DS_SMAP_MSL`, `DS_WDBC`) are attached to no spec, so they never reach the
table. An earlier draft of this round's plan counted all 11 and reported "6 of 11 altered, 5 losing a
qualifier". That was an overstatement of a defect about overstatement, caught by counting instead of
trusting the count.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from qsh.models import registry  # noqa: E402

GENERATED = REPO / "report" / "generated" / "models.tex"


def _escaped(s: str) -> str:
    """`build_data.esc`, imported rather than re-implemented so the two cannot drift."""
    sys.path.insert(0, str(REPO / "report"))
    from build_data import esc  # noqa: PLC0415

    return esc(s)


def _published_licences() -> set[str]:
    return {s.dataset.licence for s in registry._SPECS}


def test_there_are_licences_to_check() -> None:
    """A parse that finds nothing passes every assertion below for the wrong reason."""
    lic = _published_licences()
    assert len(lic) >= 5, f"only {len(lic)} distinct spec licences found; has the registry moved?"
    assert GENERATED.exists(), f"{GENERATED.relative_to(REPO)} is missing - run report/build_data.py"


def test_every_published_licence_appears_in_full() -> None:
    """The whole sentence, not its first clause and not its first 22 characters."""
    tex = GENERATED.read_text()
    missing = sorted(lic for lic in _published_licences() if _escaped(lic) not in tex)
    assert not missing, (
        "these dataset licences do not appear in full in the generated report table:\n  "
        + "\n  ".join(repr(m) for m in missing)
        + "\n\nA licence rendered without its qualifier is a STRONGER claim than the licence. "
        "'CC-BY-4.0 asserted by ' tells a reader the corpus is CC-BY-4.0; the sentence exists to say "
        "the upstream grant behind that assertion is not verifiable. Print the licence whole, and put "
        "the short identifier in the models table if the column needs to stay narrow."
    )


def test_no_rendered_cell_is_a_truncation_of_a_licence() -> None:
    """The general form: any proper prefix of a source licence, standing alone in a cell.

    Catches `split(";")` and `[:22]` with one predicate, and keeps catching them if the width or the
    separator changes.
    """
    licences = _published_licences()
    # A cell that EXACTLY equals some published licence is that licence, even when it also happens to
    # be a prefix of a longer one. `CC-BY-4.0` is the live case: it is OPS-SAT-AD's whole licence and
    # also the first nine characters of BreastMNIST's. Without this the gate reports a correct cell,
    # and a gate that cries wolf is one someone silences.
    exact = {_escaped(lic) for lic in licences}
    offenders: list[str] = []
    for line in GENERATED.read_text().splitlines():
        if "&" not in line:
            continue
        for cell in (c.strip().rstrip("\\").strip() for c in line.split("&")):
            if not cell or cell in exact:
                continue
            for lic in licences:
                esc = _escaped(lic)
                if esc.startswith(cell) and len(cell) >= 8:
                    offenders.append(f"{cell!r} is a truncation of {lic!r}")
    assert not offenders, (
        "these table cells are proper prefixes of a dataset licence:\n  "
        + "\n  ".join(sorted(set(offenders)))
        + "\n\nBoth truncations in `build_data.py` cut from the end, which is where hedges live. "
        "Removing only one of them leaves the defect this check exists for."
    )
