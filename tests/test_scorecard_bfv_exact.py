"""The integer scorecard, and the one property it has that a CKKS student cannot.

A CKKS student can promise that its encrypted output approximates its plaintext output to a
precision bound. An integer scorecard under BFV reproduces it EXACTLY, and that is the reason the
scheme pair exists in this project. These tests pin both halves: that the fit recovers integer
structure, and that BFV evaluation is bit-exact where CKKS is not.
"""
from __future__ import annotations

import numpy as np
import pytest

from qsh.models.scorecard import fit_scorecard


def test_recovers_a_known_integer_rule():
    """A scorecard fitted on data generated by an integer rule should find that rule."""
    rng = np.random.default_rng(0)
    X = rng.integers(0, 5, size=(600, 6))
    y = ((X[:, 0] * 2 + X[:, 3] - X[:, 1]) > 6).astype(int)

    sc = fit_scorecard(X, y, coef_range=5, max_features=4, rounds=4, seed=0)

    assert sc.predict(X).tolist() == y.tolist(), "should separate a linearly-separable integer rule"
    # The generating features must be selected and the irrelevant ones left at zero.
    assert sc.w[0] > 0 and sc.w[1] < 0 and sc.w[3] > 0
    assert sc.w[2] == 0 and sc.w[4] == 0 and sc.w[5] == 0
    assert sc.n_nonzero <= 4, "the sparsity cap must bind"


def test_scores_are_integers():
    """Not cosmetic: a float score would reintroduce the quantisation question BFV removes."""
    rng = np.random.default_rng(1)
    X = rng.integers(0, 4, size=(120, 5))
    y = (X[:, 0] > 2).astype(int)
    sc = fit_scorecard(X, y, coef_range=3, rounds=2, seed=1)
    assert np.issubdtype(sc.score(X).dtype, np.integer)
    assert isinstance(sc.b, int)


def test_method_is_labelled_not_claimed_optimal():
    """`method` distinguishes a proved optimum from the best a search found. They are not the same
    claim and this project does not report them as one."""
    rng = np.random.default_rng(2)
    X = rng.integers(0, 3, size=(80, 4))
    sc = fit_scorecard(X, (X[:, 1] > 1).astype(int), coef_range=2, rounds=2, seed=2)
    assert sc.method in {"milp-exact", "coordinate-search"}
    assert sc.method == "coordinate-search", "the current solver path is the heuristic one"


@pytest.mark.slow
def test_bfv_evaluates_the_scorecard_exactly_where_ckks_does_not():
    """The load-bearing property. BFV returns the integer; CKKS returns a real that rounds to it."""
    ts = pytest.importorskip("tenseal")
    rng = np.random.default_rng(0)
    X = rng.integers(0, 5, size=(200, 8))
    y = ((X[:, 0] * 3 + X[:, 5] - X[:, 2] * 2) > 8).astype(int)
    sc = fit_scorecard(X, y, coef_range=5, max_features=5, rounds=3, seed=0)
    plain = sc.score(X)

    bfv = ts.context(ts.SCHEME_TYPE.BFV, poly_modulus_degree=8192, plain_modulus=1032193)
    for i in range(20):
        v = ts.bfv_vector(bfv, X[i].tolist())
        got = int(np.sum(np.array((v * sc.w.tolist()).decrypt()))) + int(sc.b)
        assert got == int(plain[i]), f"BFV must be exact, row {i}: {got} != {plain[i]}"

    ckks = ts.context(ts.SCHEME_TYPE.CKKS, poly_modulus_degree=8192,
                      coeff_mod_bit_sizes=[60, 40, 40, 60])
    ckks.global_scale = 2 ** 40
    v = ts.ckks_vector(ckks, X[0].astype(float).tolist())
    approx = float(np.sum(np.array((v * sc.w.astype(float).tolist()).decrypt()))) + sc.b
    # Close, and NOT equal - which is the whole point of the comparison.
    assert approx != float(plain[0])
    assert abs(approx - float(plain[0])) < 1e-3
