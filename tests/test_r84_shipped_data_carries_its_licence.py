"""Every data file the repository ships carries its licence, the link, the credit and its changes.

WHY THIS EXISTS (Round 84)

CC BY 4.0 (section 3(a)), CC BY 3.0 IGO (section 4(a)) and CDLA-Sharing-1.0 (sections 3.1, 3.3)
each ask for more than a name when their data is shared: a link to the licence, the credit, and a
note of the changes. The ten evaluation samples the Hub repos redistribute carried a provenance
sentence and none of the rest, and DATA_LICENSES.md section 2c listed that as an open change. The
data and weights generated by the repository itself carried no licence at all; the owner chose the
repository's Apache-2.0 for them. And the attribution gate read only the datasets attached to a
model, so PaySim, shipped in the bundled demo sample under CC BY-SA 4.0, kept an empty credit line.

WHAT IS ASSERTED

- Every evaluation sample, overlay, held-out payload and bundled sample states `licence` and a
  `licence_url` that matches it, a `modifications` note, and an `attribution` wherever its licence
  asks for a credit (everything but Apache-2.0 and CC0).
- The sample generator writes those fields for every model it builds, from the registry.
- The telecom data and weights generated here say Apache-2.0 in each file, the registry records it,
  and the Hub card names it `license: apache-2.0`.
- The PaySim TSV header and the medical and finance QCNN weights carry their licence's link and
  their corpus's credit.
- DATA_LICENSES.md no longer records any of this as missing.

On the base commit (de1111c) every test here fails.
"""

from __future__ import annotations

import glob
import importlib.util
import json
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
PUBLIC = REPO / "web" / "public" / "data"

LINKS = {
    "CC-BY-4.0": "https://creativecommons.org/licenses/by/4.0/",
    "CC-BY-SA-4.0": "https://creativecommons.org/licenses/by-sa/4.0/",
    "CC-BY-3.0-IGO": "https://creativecommons.org/licenses/by/3.0/igo/",
    "CDLA-Sharing-1.0": "https://cdla.dev/sharing-1-0/",
    "CC0-1.0": "https://creativecommons.org/publicdomain/zero/1.0/",
    "Apache-2.0": "https://www.apache.org/licenses/LICENSE-2.0",
}
NO_CREDIT_REQUIRED = ("Apache-2.0", "CC0-1.0")

SHIPPED = sorted(glob.glob(str(REPO / "models" / "*" / "eval_sample.json"))) + [
    str(PUBLIC / rel) for rel in (
        "medical/breast_cancer_sample.json", "medical/real_2d.json", "satellite/real_2d.json",
        "satellite/opssat_segments.json", "finance/real_2d.json", "finance/student_heldout.json",
        "finance/paysim_sample.json", "genomics/real_2d.json", "genomics/pgs000072_breast_cancer.json",
        "telecom/real_2d.json", "telecom/student_heldout.json", "telecom_nidd/real_2d.json")] + [
    str(REPO / "walkthroughs" / "public" / "nidd_copies_excerpt.json")]


def _head(licence: str) -> str:
    """The identifier at the front of a registry licence string."""
    return licence.split(";")[0].split(" asserted by ")[0].split(" (")[0].strip()


@pytest.mark.parametrize("path", SHIPPED, ids=lambda p: str(Path(p).relative_to(REPO)))
def test_each_shipped_file_carries_its_licence_link_credit_and_changes(path: str) -> None:
    d = json.loads(Path(path).read_text())
    head = _head(d.get("licence") or "")
    assert head in LINKS, f"{path}: licence {d.get('licence')!r} is not one this test knows"
    assert d.get("licence_url") == LINKS[head], (path, d.get("licence_url"))
    assert (d.get("modifications") or "").strip(), f"{path}: no change note"
    if head not in NO_CREDIT_REQUIRED:
        assert (d.get("attribution") or "").strip(), f"{path}: {head} asks for a credit and none is given"


def test_the_sample_generator_writes_the_fields_for_every_model() -> None:
    spec = importlib.util.spec_from_file_location("pmi", REPO / "scripts" / "prep_model_inputs.py")
    pmi = importlib.util.module_from_spec(spec)
    argv, sys.argv = sys.argv, ["prep_model_inputs.py"]
    try:
        spec.loader.exec_module(pmi)
    finally:
        sys.argv = argv
    for key in pmi._MODEL_KEY.values():
        fields = pmi._licence_fields(key)
        assert fields["licence_url"] == LINKS[_head(fields["licence"])], key
        assert fields["modifications"].strip(), key
        ordered = pmi._ordered(key, {"provenance": "p", "samples": []}, "a split")
        assert list(ordered)[:3] == ["provenance", "split", "licence"], (key, list(ordered))


def test_the_generated_telecom_data_and_weights_say_apache_2() -> None:
    from qsh.models import registry

    assert registry.DS_QKD_ATTACK_SYNTH.licence == "Apache-2.0"
    for rel in ("telecom/real_2d.json", "telecom/student_heldout.json"):
        d = json.loads((PUBLIC / rel).read_text())
        assert (d["licence"], d["licence_url"]) == ("Apache-2.0", LINKS["Apache-2.0"]), rel
    for f in ("models/qcnn_telecom/weights.json", "web/public/data/telecom/qcnn_weights.json",
              "models/qcnn_telecom_q7/weights.json", "web/public/data/telecom/qcnn_weights_q7.json"):
        assert "Apache-2.0" in json.loads((REPO / f).read_text())["provenance"], f
    for f in ("models/telecom_ids_student/weights.json", "web/public/data/telecom/student_weights.json"):
        assert json.loads((REPO / f).read_text())["licence"] == "Apache-2.0", f
    spec = importlib.util.spec_from_file_location("publish_hf", REPO / "scripts" / "publish_hf.py")
    hf = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(hf)
    assert hf._hub_licence(registry.DS_QKD_ATTACK_SYNTH.licence) == ["license: apache-2.0"]


def test_the_paysim_tsv_and_the_qcnn_weights_carry_link_and_credit() -> None:
    head = [ln for ln in (REPO / "data" / "finance" / "paysim_sample.tsv").read_text().splitlines()
            if ln.startswith("#")]
    text = " ".join(head)
    assert LINKS["CC-BY-SA-4.0"] in text and "Lopez-Rojas" in text and "Changes:" in text
    for f, link, credit in (("models/qcnn_medical/weights.json", LINKS["CC-BY-4.0"], "doi:10.24432/C5DW2B"),
                            ("web/public/data/medical/qcnn_weights.json", LINKS["CC-BY-4.0"], "doi:10.24432/C5DW2B"),
                            ("models/qcnn_finance/weights.json", LINKS["CC-BY-SA-4.0"], "Lopez-Rojas"),
                            ("web/public/data/finance/qcnn_weights.json", LINKS["CC-BY-SA-4.0"], "Lopez-Rojas")):
        prov = json.loads((REPO / f).read_text())["provenance"]
        assert link in prov and credit in prov, f


def test_the_register_of_licences_records_nothing_of_this_as_missing() -> None:
    text = (REPO / "DATA_LICENSES.md").read_text(encoding="utf-8")
    for stale in ("none stated", "carry no stated licence", "under no stated licence",
                  "with no `license_link`", "what is still missing"):
        assert stale not in text, stale
