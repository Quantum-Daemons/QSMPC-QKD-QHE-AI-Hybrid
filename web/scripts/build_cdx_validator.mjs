// Writes src/lib/generated/cdx17Validate.js: the CycloneDX 1.7 schema compiled by Ajv into standalone code (Round 86,
// the owner's choice of 2026-11-23), so the Validations page checks the CBOM in the tab. The page's
// Content-Security-Policy has no 'unsafe-eval', so Ajv cannot compile there; precompiled code is plain JavaScript.
//
// The schemas are the vendored ones tests/test_r86_cbom.py validates against (schemas/cyclonedx), read the way that
// test reads them: draft-07, no format checked (Python's jsonschema checks none without a FormatChecker), and keywords
// JSON Schema does not define, such as CycloneDX's "meta:enum", ignored (strict: false). The file is committed because
// the web image builds from web/ alone and CI typechecks before it builds; tests/test_r86_cbom_in_the_tab.py requires
// it to be what this script writes, and to agree with Python's jsonschema on the CBOM and on documents made wrong.
// The page loads it only when the CBOM panel mounts, as its own chunk.
//
//   node scripts/build_cdx_validator.mjs           write it
//   node scripts/build_cdx_validator.mjs --check   exit 1 if the committed file is not what this writes
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";

const SCHEMAS = new URL("../../schemas/cyclonedx/", import.meta.url);
const OUT = fileURLToPath(new URL("../src/lib/generated/cdx17Validate.js", import.meta.url));
const ROOT = "http://cyclonedx.org/schema/bom-1.7.schema.json";

// Keywords that only annotate a schema. Ajv would embed them in the code as data (the raw output was 1.2 MB, mostly
// CycloneDX's descriptions); validation never reads them. They are dropped where a schema stands, and never from
// `properties` (whose keys are property names: "description" is one of CycloneDX's), `enum` or `const` (data).
const ANNOTATIONS = new Set(["title", "description", "examples", "$comment", "meta:enum", "deprecated", "default", "readOnly", "writeOnly"]);
const NAMED_SCHEMAS = new Set(["properties", "patternProperties", "definitions", "$defs", "dependencies"]);
const DATA = new Set(["enum", "const", "required", "type"]);

export function stripAnnotations(node) {
  if (Array.isArray(node)) return node.map(stripAnnotations);
  if (!node || typeof node !== "object") return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (ANNOTATIONS.has(k)) continue;
    if (NAMED_SCHEMAS.has(k) && v && typeof v === "object" && !Array.isArray(v)) {
      out[k] = Object.fromEntries(Object.entries(v).map(([name, sub]) => [name, stripAnnotations(sub)]));
    } else {
      out[k] = DATA.has(k) ? v : stripAnnotations(v);
    }
  }
  return out;
}

export function schemas() {
  return ["spdx.schema.json", "jsf-0.82.schema.json", "cryptography-defs.schema.json", "bom-1.7.schema.json"]
    .map((name) => JSON.parse(readFileSync(new URL(name, SCHEMAS), "utf8")));
}

export function validatorSource() {
  // inlineRefs: false compiles each definition once and calls it, where inlining copied CycloneDX's shared definitions
  // into every place that refers to them (833 KB of code against 728 KB).
  const ajv = new Ajv({ strict: false, validateFormats: false, allErrors: false, inlineRefs: false, code: { source: true, esm: true, lines: false } });
  for (const schema of schemas()) ajv.addSchema(stripAnnotations(schema));
  let code = standaloneCode(ajv, ajv.getSchema(ROOT));
  // Ajv names its runtime helpers with require(); the page is an ES module, so each becomes an import.
  const helpers = [...new Set([...code.matchAll(/require\("(ajv\/dist\/runtime\/[a-z0-9_]+)"\)\.default/g)].map((m) => m[1]))];
  helpers.forEach((h, i) => { code = code.split(`require("${h}").default`).join(`__ajvRuntime${i}`); });
  if (/\brequire\(/.test(code)) throw new Error("the standalone code still calls require()");
  const header = [
    "// GENERATED by web/scripts/build_cdx_validator.mjs from schemas/cyclonedx (CycloneDX 1.7, Apache-2.0) with Ajv 8.20.0 (MIT).",
    "// Do not edit: run `node scripts/build_cdx_validator.mjs` in web/. tests/test_r86_cbom_in_the_tab.py checks it is current.",
    "/* eslint-disable */",
    "// @ts-nocheck",
    // Each helper is a CommonJS module whose function is `exports.default`. A bundler in Node's mode hands a default
    // import the whole `exports` object, Vite's build hands it `exports.default`; the namespace and a pick work in both.
    ...helpers.map((h, i) => `import * as __ajvRuntimeNs${i} from "${h}.js";`),
    "const __ajvPick = (ns) => [ns.default, ns.default && ns.default.default, ns].find((f) => typeof f === \"function\");",
    ...helpers.map((h, i) => `const __ajvRuntime${i} = __ajvPick(__ajvRuntimeNs${i});`),
  ].join("\n");
  return `${header}\n${code.replace(/^"use strict";\n?/, "")}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const src = validatorSource();
  if (process.argv.includes("--check")) {
    let now = "";
    try { now = readFileSync(OUT, "utf8"); } catch { /* missing */ }
    if (now !== src) { console.error("src/lib/generated/cdx17Validate.js is not what build_cdx_validator.mjs writes; run it."); process.exit(1); }
    console.log("cdx17Validate.js is current");
  } else {
    writeFileSync(OUT, src);
    console.log(`wrote ${OUT} (${src.length} bytes)`);
  }
}
